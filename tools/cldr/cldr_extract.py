#!/usr/bin/env python3
"""Fetch the pinned Unicode CLDR release and extract what libniji's locale sources are made from.

    python3 -I tools/cldr/cldr_extract.py [--zip cldr-common-49.zip] [--check]

Without --zip the release is downloaded from unicode.org into a new temporary directory; with
--zip a copy fetched earlier is used. Either way its SHA-256 must equal PIN_SHA256 below, or
nothing is written. The archive is read in place (never unpacked to disk). Output, all under
spec/cldr/<PIN_VERSION>/ (D-31.27, LOCALE-SOURCES-GEN):

* locales.tsv: for each locale name of spec/cldr/locale-names.tsv that CLDR covers, the CLDR
  values its locale source is made from, resolved through CLDR's inheritance (parent locales,
  root, aliases) so the generator (xtask/src/locales.rs) needs no CLDR logic of its own;
* territories.tsv: per territory, the supplemental data (currency, its digits, paper size,
  measurement system, first day of the week, ISO 3166 codes);
* allkeys_CLDR.txt: CLDR's root collation (the DUCET with CLDR's root changes), copied;
* LICENSE: the Unicode License v3 text shipped in the archive, copied.

This script is run by hand when the pin changes (a reviewed change of PIN_* and the outputs);
the build never fetches anything. --check writes nothing and fails if an output would change.
"""

import hashlib
import io
import os
import re
import sys
import tempfile
import urllib.request
import xml.etree.ElementTree as ET
import zipfile

PIN_VERSION = "49"
PIN_URL = "https://unicode.org/Public/cldr/49/cldr-common-49.zip"
PIN_SHA256 = "78403d8d6fb1fed6e208bf9001bf5be00bb5abfd9f8110dae062bf49309d6a89"

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
NAMES = os.path.join(ROOT, "spec", "cldr", "locale-names.tsv")
OUT = os.path.join(ROOT, "spec", "cldr", PIN_VERSION)
HEADER = "# @generated by tools/cldr/cldr_extract.py from %s (sha256 %s); do not edit\n" % (PIN_URL, PIN_SHA256)

# Attributes that tell sibling elements apart in a CLDR path (draft, references are not).
DISTINGUISHING = ("type", "alt", "numberSystem", "count", "id", "key")
# Locale modifiers of the reference's names and the CLDR subtag each selects.
MODIFIER_SCRIPT = {"latin": "Latn", "cyrillic": "Cyrl", "devanagari": "Deva", "iqtelif": "Latn"}
MODIFIER_VARIANT = {"valencia": "valencia"}
DAYS = ("sun", "mon", "tue", "wed", "thu", "fri", "sat")


def fetch(path):
    if path is None:
        d = tempfile.mkdtemp(prefix="cldr-")
        path = os.path.join(d, os.path.basename(PIN_URL))
        with urllib.request.urlopen(PIN_URL, timeout=300) as r, open(path, "wb") as f:
            while True:
                b = r.read(1 << 20)
                if not b:
                    break
                f.write(b)
    data = open(path, "rb").read()
    got = hashlib.sha256(data).hexdigest()
    if got != PIN_SHA256:
        sys.exit("cldr_extract: %s has sha256 %s, the pin is %s: nothing written" % (path, got, PIN_SHA256))
    return zipfile.ZipFile(io.BytesIO(data))


def flatten(root):
    """Map each leaf path of an LDML tree to its text; aliases map to ('alias', target path)."""
    flat, alias = {}, {}

    def walk(e, path):
        key = e.tag
        attrs = ["@%s=%s" % (a, e.get(a)) for a in DISTINGUISHING if e.get(a) is not None]
        if attrs:
            key += "[" + ",".join(attrs) + "]"
        p = path + (key,)
        if e.tag == "alias":
            alias[path] = e.get("path")
            return
        kids = list(e)
        if not kids:
            if e.get("draft") == "unconfirmed":
                return
            if e.text is not None and p not in flat:
                flat[p] = e.text
        for k in kids:
            walk(k, p)

    walk(root, ())
    return flat, alias


def rel(base, path):
    """Apply an alias's relative XPath to the path of its parent."""
    out = list(base)
    for step in path.split("/"):
        if step == "..":
            out.pop()
        else:
            m = re.fullmatch(r"(\w+)(?:\[@(\w+)='([^']*)'\])?", step)
            if not m:
                raise ValueError("alias step %r" % step)
            out.append(m.group(1) + ("[@%s=%s]" % (m.group(2), m.group(3)) if m.group(2) else ""))
    return tuple(out)


class Cldr:
    def __init__(self, z):
        self.z = z
        self.files = {}
        self.main = {n[len("common/main/"):-4] for n in z.namelist()
                     if n.startswith("common/main/") and n.endswith(".xml")}
        sup = ET.fromstring(z.read("common/supplemental/supplementalData.xml"))
        self.sup = sup
        self.parents = {}
        for pl in sup.iter("parentLocale"):
            if pl.get("component") is None:
                for l in pl.get("locales").split():
                    self.parents[l] = pl.get("parent")
        likely = ET.fromstring(z.read("common/supplemental/likelySubtags.xml"))
        self.likely = {e.get("from"): e.get("to") for e in likely.iter("likelySubtag")}
        # ISO 639-2 codes: CLDR lists each three-letter code that has a two-letter one as an alias of
        # it ("overlong": the terminology code; "bibliographic": the B code where it differs).
        meta = ET.fromstring(z.read("common/supplemental/supplementalMetadata.xml"))
        self.lang3 = {}
        for e in meta.iter("languageAlias"):
            t, r, why = e.get("type"), e.get("replacement"), e.get("reason")
            if why in ("overlong", "bibliographic") and len(t) == 3 and r and "_" not in r:
                self.lang3.setdefault((r, why), t)

    def flat(self, loc):
        if loc not in self.files:
            self.files[loc] = flatten(ET.fromstring(self.z.read("common/main/%s.xml" % loc)))
        return self.files[loc]

    def chain(self, loc):
        out = []
        while loc:
            out.append(loc)
            if loc == "root":
                break
            if loc in self.parents:
                loc = self.parents[loc]
            elif "_" in loc:
                loc = loc.rsplit("_", 1)[0]
            else:
                loc = "root"
        return [l for l in out if l in self.main]

    def get(self, loc, path, depth=0):
        if depth > 20:
            raise ValueError("alias loop at %r" % (path,))
        ch = self.chain(loc)
        for l in ch:
            v = self.flat(l)[0].get(path)
            if v is not None:
                return v
        for n in range(len(path) - 1, 0, -1):
            pre = path[:n]
            for l in ch:
                a = self.flat(l)[1].get(pre)
                if a is not None:
                    return self.get(loc, rel(pre, a) + path[n:], depth + 1)
        return None

    def cldr_id(self, name):
        """The CLDR locale for a reference locale name (language_TERRITORY[@modifier]), or None."""
        base, _, mod = name.partition("@")
        lang, _, terr = base.partition("_")
        cands = []
        if mod in MODIFIER_VARIANT:
            cands.append("%s_%s_%s" % (lang, terr, MODIFIER_VARIANT[mod]))
        if mod in MODIFIER_SCRIPT:
            cands.append("%s_%s_%s" % (lang, MODIFIER_SCRIPT[mod], terr))
        cands.append(base)
        for k in (base, lang):
            t = self.likely.get(k)
            if t:
                parts = t.split("_")
                if len(parts) == 3:
                    cands.append("%s_%s_%s" % (lang, parts[1], terr))
        # The language CLDR has without this territory (eu_FR: Basque, with France's territory data
        # from the supplemental tables); a language CLDR lacks is never guessed (D-31.27).
        if mod in MODIFIER_SCRIPT:
            cands.append("%s_%s" % (lang, MODIFIER_SCRIPT[mod]))
        cands.append(lang)
        for c in cands:
            if c in self.main:
                return c
        return None


def P(*steps):
    return ("ldml",) + steps


def gregorian(*steps):
    return P("dates", "calendars", "calendar[@type=gregorian]", *steps)


def numbers(c, loc, out):
    ns = c.get(loc, P("numbers", "defaultNumberingSystem")) or "latn"
    out["numbers.system"] = ns
    for s in ("decimal", "group", "minusSign", "plusSign", "percentSign"):
        v = c.get(loc, P("numbers", "symbols[@numberSystem=%s]" % ns, s))
        if v is None:
            v = c.get(loc, P("numbers", "symbols[@numberSystem=latn]", s))
        out["numbers.symbol." + s] = v
    for s in ("currencyDecimal", "currencyGroup"):
        v = c.get(loc, P("numbers", "symbols[@numberSystem=%s]" % ns, s))
        if v is not None:
            out["numbers.symbol." + s] = v
    out["numbers.decimalFormat"] = c.get(loc, P("numbers", "decimalFormats[@numberSystem=%s]" % ns,
                                                  "decimalFormatLength", "decimalFormat", "pattern")) \
        or c.get(loc, P("numbers", "decimalFormats[@numberSystem=latn]", "decimalFormatLength",
                        "decimalFormat", "pattern"))
    out["numbers.currencyFormat"] = c.get(loc, P("numbers", "currencyFormats[@numberSystem=%s]" % ns,
                                                   "currencyFormatLength", "currencyFormat[@type=standard]", "pattern")) \
        or c.get(loc, P("numbers", "currencyFormats[@numberSystem=latn]", "currencyFormatLength",
                        "currencyFormat[@type=standard]", "pattern"))


def extract(c, name, terr, currency):
    loc = c.cldr_id(name)
    if loc is None:
        return None
    out = {"cldr.id": loc}
    lang = loc.split("_")[0]
    out["names.language"] = c.get(loc, P("localeDisplayNames", "languages", "language[@type=%s]" % lang))
    out["names.territory"] = c.get(loc, P("localeDisplayNames", "territories", "territory[@type=%s]" % terr))
    out["names.language.en"] = c.get("en", P("localeDisplayNames", "languages", "language[@type=%s]" % lang))
    out["names.territory.en"] = c.get("en", P("localeDisplayNames", "territories", "territory[@type=%s]" % terr))
    for ctx in ("format", "stand-alone"):
        for w in ("wide", "abbreviated"):
            for i in range(1, 13):
                out["months.%s.%s.%d" % (ctx, w, i)] = c.get(loc, gregorian(
                    "months", "monthContext[@type=%s]" % ctx, "monthWidth[@type=%s]" % w, "month[@type=%d]" % i))
            for d in DAYS:
                out["days.%s.%s.%s" % (ctx, w, d)] = c.get(loc, gregorian(
                    "days", "dayContext[@type=%s]" % ctx, "dayWidth[@type=%s]" % w, "day[@type=%s]" % d))
    for p in ("am", "pm"):
        out["dayPeriods." + p] = c.get(loc, gregorian(
            "dayPeriods", "dayPeriodContext[@type=format]", "dayPeriodWidth[@type=abbreviated]", "dayPeriod[@type=%s]" % p))
    for kind, el in (("date", "dateFormat"), ("time", "timeFormat"), ("dateTime", "dateTimeFormat")):
        for ln in ("full", "long", "medium", "short"):
            out["%sFormats.%s" % (kind, ln)] = c.get(loc, gregorian(
                "%sFormats" % kind, "%sLength[@type=%s]" % (el, ln), el, "pattern"))
    for skel in ("hms", "yMMMEd", "yMd"):
        out["skeleton." + skel] = c.get(loc, gregorian(
            "dateTimeFormats", "availableFormats", "dateFormatItem[@id=%s]" % skel))
    out["names.alpha3.terminology"] = c.lang3.get((lang, "overlong"))
    out["names.alpha3.bibliographic"] = c.lang3.get((lang, "bibliographic"))
    numbers(c, loc, out)
    if currency:
        out["currency.symbol"] = c.get(loc, P("numbers", "currencies", "currency[@type=%s]" % currency, "symbol"))
    for m in ("yesstr", "nostr"):
        out["posix." + m] = c.get(loc, P("posix", "messages", m))
    return out


def territories(c):
    sup = c.sup
    t = {}

    def put(codes, k, v, only_new=False):
        for cc in codes.split():
            d = t.setdefault(cc, {})
            if not (only_new and k in d):
                d[k] = v

    for e in sup.iter("territoryCodes"):
        put(e.get("type"), "alpha3", e.get("alpha3") or "")
        put(e.get("type"), "numeric", e.get("numeric") or "")
    for r in sup.find("currencyData").iter("region"):
        for cur in r.findall("currency"):
            if cur.get("to") is None and cur.get("tender") != "false":
                put(r.get("iso3166"), "currency", cur.get("iso4217"), only_new=True)
    digits = {}
    for e in sup.find("currencyData").find("fractions").findall("info"):
        digits[e.get("iso4217")] = e.get("digits")
    for cc, d in t.items():
        if "currency" in d:
            d["currency.digits"] = digits.get(d["currency"], digits["DEFAULT"])
    md = sup.find("measurementData")
    for e in md.findall("measurementSystem"):
        if e.get("category") is None:
            put(e.get("territories"), "measurement", e.get("type"))
    for e in md.findall("paperSize"):
        put(e.get("territories"), "paper", e.get("type"))
    wd = sup.find("weekData")
    for e in wd.findall("firstDay"):
        if e.get("alt") is None:
            put(e.get("territories"), "firstDay", e.get("day"))
    for e in wd.findall("weekendEnd"):
        put(e.get("territories"), "weekendEnd", e.get("day"))
    for e in wd.findall("minDays"):
        put(e.get("territories"), "minDays", e.get("count"))
    return t


def esc(v):
    return v.replace("\\", "\\\\").replace("\t", "\\t").replace("\n", "\\n")


def main(argv):
    zpath, check = None, False
    it = iter(argv)
    for a in it:
        if a == "--zip":
            zpath = next(it)
        elif a == "--check":
            check = True
        else:
            sys.exit(__doc__)
    z = fetch(zpath)
    c = Cldr(z)
    names = []
    for line in open(NAMES, encoding="utf-8"):
        if line.strip() and not line.startswith("#"):
            names.append(line.split("\t")[0])
    terr = territories(c)
    loc_lines, missing = [], []
    for name in sorted(set(names)):
        cc = name.partition("@")[0].partition("_")[2]
        if not cc:
            continue  # C: from POSIX XBD 7.3, not CLDR
        cur = terr.get(cc, {}).get("currency")
        if name.endswith("@euro"):
            cur = "EUR"
        vals = extract(c, name, cc, cur)
        if vals is None:
            missing.append(name)
            continue
        for k in sorted(vals):
            if vals[k] is not None:
                loc_lines.append("%s\t%s\t%s\n" % (name, k, esc(vals[k])))
    ter_lines = []
    for cc in sorted(terr):
        if re.fullmatch(r"[A-Z]{2}|001", cc):
            for k in sorted(terr[cc]):
                ter_lines.append("%s\t%s\t%s\n" % (cc, k, terr[cc][k]))
    outs = {
        "locales.tsv": (HEADER + "# name\tkey\tvalue (\\\\, \\t, \\n escaped); not covered: %s\n" % " ".join(missing)
                        + "".join(loc_lines)).encode(),
        "territories.tsv": (HEADER + "# territory\tkey\tvalue\n" + "".join(ter_lines)).encode(),
        "allkeys_CLDR.txt": z.read("common/uca/allkeys_CLDR.txt"),
        "LICENSE": z.read("LICENSE"),
    }
    bad = False
    for fn, body in outs.items():
        p = os.path.join(OUT, fn)
        old = open(p, "rb").read() if os.path.exists(p) else None
        if old == body:
            continue
        if check:
            print("cldr_extract: %s would change" % p)
            bad = True
        else:
            os.makedirs(OUT, exist_ok=True)
            with open(p, "wb") as f:
                f.write(body)
            print("cldr_extract: wrote %s (%d bytes)" % (p, len(body)))
    print("cldr_extract: %d names, %d not covered by CLDR %s" % (len(set(names)), len(missing), PIN_VERSION))
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
