#!/usr/bin/env python3
"""Rename the project from Liella to libniji (RENAME-NIJI-CODE, owner ruling 2026-11-16).

    python3 tools/rename_niji.py [--check | --self-test]

Run from the top of a git checkout. Renames the old name in the contents of every tracked file
outside the exclusions below, and in tracked paths (with `git mv`). Deterministic and
re-runnable: a second run changes nothing. `--check` changes nothing and exits 1 if a run would
change something (prints the files). `--self-test` checks the rules on fixed examples
(EXAMPLES, PATHS) and touches no file. No spec clause: a project rename, no behaviour.

Mapping, applied to each text in this order (the owner's table; identifier stem `niji`):

1. Kept verbatim (PROTECT): the author identity, the public repository URL (renamed by the owner
   after this lands), the internal ops names (Q6), and references to history that keeps the old
   name (handoff notes, the old repository's label).
2. Explicit spellings (EXPLICIT): fixed-size magic words keep their length; the native interface
   library becomes `libniji.so` / `-lniji`.
3. Rust v0/legacy mangled identifiers `<len>liella_x` become `<len-2>niji_x` (the length prefix
   counts the identifier, so a plain substitution would corrupt it).
4. `LIELLA` -> `NIJI` (version nodes, constants, macros, variables, `__LIELLA__`).
5. `Liella` -> `Niji` inside an identifier (`LiellaTm`) and, in `.rs` files, where a bare `Liella`
   is a Rust type or enum variant (RUST_IDENT), else `libniji` (prose, messages; owner Q1).
6. `liella` -> `niji` (crates, modules, paths, packages, run-time names, `+liella`).

Exclusions (EXCLUDE): history (handoff/, records/, validation/results/ and results/, the dated
measurement records, the release notes) and
the prose RENAME-NIJI-DOCS rewrites (docs/, README.md, plan/, spec/ prose, the top-level
documents). Binary files (not UTF-8, or holding a NUL byte, unless source code by its suffix)
change only through equal-length EXPLICIT spellings.

Clause stub files that `cargo xtask stubs` still writes (its @generated mark and no specified
`#[test]`, `stubs_owned`) quote the excluded spec prose: they are left to that generator.
"""

import os
import re
import subprocess
import sys

# Paths (prefixes) never rewritten.
EXCLUDE = (
    "handoff/",
    "records/",
    "validation/results/",
    "results/",
    "docs/",
    "plan/",
    "spec/behaviour/",
    "spec/security/",
    "spec/unicode/",
    "spec/ERRATA.md",
    "spec/clauses.tsv",
    "spec/schedule.tsv",
    "README.md",
    "RELEASE-NOTES.md",
    "AI_POLICY.md",
    "CLAUDE.md",
    "CODE_OF_CONDUCT.md",
    "CONTRIBUTING.md",
    "SECURITY.md",
    "implementation-plan.md",
    "glibc-functional-spec.md",
    "tools/rename_niji.py",
)

# Kept verbatim wherever they appear.
PROTECT = (
    "Liella Maintainers <liella@koiren.ai>",
    "liella@koiren.ai",
    "github.com/duskglow/liella",
    "liella-ops",
    "src/liella",
    "liella-historic",
    "LIELLA-UTILITIES-DESIGN",
    # The compat records' key for Liella's behaviour (records/ is history, so the reader keeps it).
    '"glibc", "liella", "restore"',
    # Test names a decision record cites (records/decisions/D-27/D-27.43.toml).
    "reference_ldconfig_lists_liella_cache_alike",
    "reference_loader_resolves_through_liella_cache",
)

# Explicit spellings, applied before the general rules (old, new).
EXPLICIT = (
    ("LIELLANC", "NIJI_NSC"),  # the name-service cache's 8-byte magic word keeps its size
    ('b"liella!!"', 'b"niji!!!!"'),  # an 8-byte test secret keeps its size
    ("libliella_native", "libniji"),
    ("-lliella_native", "-lniji"),
)

MANGLED = re.compile(r"(?<![0-9])([0-9]+)(liella)")
CAMEL = re.compile(r"Liella(?=[A-Za-z0-9_])")
# A bare `Liella` used as a Rust identifier (a type or an enum variant: `heap::Liella`,
# `struct Liella`, `for Liella {`, a `    Liella,` variant line, or a type-name prefix test
# `starts_with("Liella")`) becomes `Niji`, an upper camel case name, not the prose spelling.
# Applied to `.rs` files only.
RUST_IDENT = re.compile(
    r"(?<=::)Liella\b|(?<=\bstruct )Liella\b|(?<=\bfor )Liella(?= \{)|(?<=^    )Liella(?=,$)"
    r'|(?<=starts_with\(")Liella(?="\))',
    re.M,
)


STUBS_MARK = "@generated by `cargo xtask stubs`"
# Source code is text even when it holds a literal NUL byte.
SOURCE_SUFFIXES = (".rs", ".c", ".h", ".S", ".py", ".sh")


def stubs_owned(text):
    """A clause stub file `cargo xtask stubs` still writes (no specified `#[test]` yet): it
    quotes the excluded spec prose, so the stubs generator owns its text, not this script."""
    return STUBS_MARK in text[:200] and not any(l.strip() == "#[test]" for l in text.splitlines())


def as_text(path, data):
    """The file's text, or None for data: not UTF-8, or holding a NUL byte (fuzz seeds, caches),
    except source code, where a NUL is a literal byte in a string (crates/core/src/time/zone.rs)."""
    try:
        text = data.decode("utf-8")
    except UnicodeDecodeError:
        return None
    return text if path.endswith(SOURCE_SUFFIXES) or "\0" not in text else None


def excluded(path):
    return any(path == p or (p.endswith("/") and path.startswith(p)) for p in EXCLUDE)


def mangled(text):
    out = []
    last = 0
    for m in MANGLED.finditer(text):
        n = int(m.group(1))
        ident = text[m.start(2):m.start(2) + n]
        if n >= 6 and len(ident) == n and re.fullmatch(r"[A-Za-z0-9_]+", ident):
            out.append(text[last:m.start()])
            out.append(str(n - 2) + "niji")
            last = m.end()
    out.append(text[last:])
    return "".join(out)


def rename_text(text, rust=False):
    keep = {}
    for i, p in enumerate(PROTECT):
        token = "\0P%d\0" % i
        keep[token] = p
        text = text.replace(p, token)
    for old, new in EXPLICIT:
        text = text.replace(old, new)
    text = mangled(text)
    text = text.replace("LIELLA", "NIJI")
    if rust:
        text = RUST_IDENT.sub("Niji", text)
    text = CAMEL.sub("Niji", text)
    text = text.replace("Liella", "libniji")
    text = text.replace("liella", "niji")
    for token, p in keep.items():
        text = text.replace(token, p)
    return text


def rename_bytes(data):
    for old, new in EXPLICIT:
        if len(old) == len(new):
            data = data.replace(old.encode(), new.encode())
    return data


def rename_path(path):
    head, _, name = path.rpartition("/")
    parts = [rename_text(p) for p in head.split("/")] if head else []
    return "/".join(parts + [rename_text(name)])


def tracked():
    out = subprocess.run(["git", "ls-files", "-z"], check=True, capture_output=True).stdout
    return sorted(p for p in out.decode().split("\0") if p)


# The rules on fixed examples (`--self-test`; no spec clause: a project rename): input, output.
EXAMPLES = (
    ("liella-boundary liella_kernel::fd crate liella", "niji-boundary niji_kernel::fd crate niji"),
    ("LIELLA_NATIVE_1 LIELLA_COMPAT_LEGACY_DECLS __LIELLA__ -DLIELLA_PREFIX=/", "NIJI_NATIVE_1 NIJI_COMPAT_LEGACY_DECLS __NIJI__ -DNIJI_PREFIX=/"),
    ("Liella's loader; LiellaTm; \"Liella\"", "libniji's loader; NijiTm; \"libniji\""),
    ("_RNvNtCs1a_15liella_boundary3cpu4init 10liella_mem7copy_u8", "_RNvNtCs1a_13niji_boundary3cpu4init 8niji_mem7copy_u8"),
    ("x86_64 2.39+liella20261116.1-1 liella6-dev /usr/lib/liella", "x86_64 2.39+niji20261116.1-1 niji6-dev /usr/lib/niji"),
    ("-lliella_native libliella_native.so *b\"LIELLANC\"", "-lniji libniji.so *b\"NIJI_NSC\""),
    ("Liella Maintainers <liella@koiren.ai> github.com/duskglow/liella ~/src/liella-ops", "Liella Maintainers <liella@koiren.ai> github.com/duskglow/liella ~/src/liella-ops"),
    ("(liella-historic:handoff/x.md) handoff/LIELLA-UTILITIES-DESIGN.md", "(liella-historic:handoff/x.md) handoff/LIELLA-UTILITIES-DESIGN.md"),
)
# Rust identifier rule (`.rs` files): input, output.
RUST_EXAMPLES = (
    ("pub struct Liella;\nunsafe impl GlobalAlloc for Liella {\nstatic A: liella_boundary::heap::Liella = x;\n",
     "pub struct Niji;\nunsafe impl GlobalAlloc for Niji {\nstatic A: niji_boundary::heap::Niji = x;\n"),
    ("enum Build {\n    Liella,\n    LiellaV3,\n}\n    Build::Liella | Build::LiellaSorted => {}\n",
     "enum Build {\n    Niji,\n    NijiV3,\n}\n    Build::Niji | Build::NijiSorted => {}\n"),
    ("// reach Liella's export; Liella the block, for Liella.\n\"Liella's interpreter\"\n",
     "// reach libniji's export; libniji the block, for libniji.\n\"libniji's interpreter\"\n"),
    ('if t.starts_with("Liella") {\nwithout(got, &ADDED, "Liella");\n["glibc", "liella", "restore"]\n'
     "fn reference_loader_resolves_through_liella_cache() {}\n",
     'if t.starts_with("Niji") {\nwithout(got, &ADDED, "libniji");\n["glibc", "liella", "restore"]\n'
     "fn reference_loader_resolves_through_liella_cache() {}\n"),
)
PATHS = (
    ("include/liella/native.h", "include/niji/native.h"),
    ("tools/deb/liella-gcc.1", "tools/deb/niji-gcc.1"),
    ("handoff/liella.md", None),
    ("records/compat/COMPAT-1.toml", None),
    ("docs/x.md", None),
    ("results/x.md", None),
    ("crates/core/src/lib.rs", "crates/core/src/lib.rs"),
)


def self_test():
    bad = []
    for old, new in EXAMPLES:
        got = rename_text(old)
        if got != new:
            bad.append("rename_text(%r) = %r, want %r" % (old, got, new))
        if rename_text(new) != new:
            bad.append("rename_text is not idempotent on %r" % new)
    for old, new in RUST_EXAMPLES:
        got = rename_text(old, rust=True)
        if got != new:
            bad.append("rename_text(%r, rust) = %r, want %r" % (old, got, new))
        if rename_text(new, rust=True) != new:
            bad.append("rename_text(rust) is not idempotent on %r" % new)
    if rename_text("pub struct Liella;") != "pub struct libniji;":
        bad.append("the Rust identifier rule applies outside .rs files")
    stub = "// " + STUBS_MARK + " from glibc-functional-spec.md.\n// a real #[test] fn\nclause!(x, r##\"Liella\"##);\n"
    if not stubs_owned(stub) or stubs_owned(stub + "#[test]\nfn x() {}\n") or stubs_owned("Liella"):
        bad.append("stubs_owned: a stub file without a specified #[test] only")
    if (as_text("a/zone.rs", b"//! Liella\nb\"\0\"") is None or as_text("fuzz/seeds/x", b"/liella\0") is not None
            or as_text("a.c", b"\xff") is not None or as_text("a.txt", b"Liella") != "Liella"):
        bad.append("as_text: source code with a NUL is text; data with a NUL or bad UTF-8 is not")
    if rename_bytes(b"\0LIELLANC\0liella") != b"\0NIJI_NSC\0liella":
        bad.append("rename_bytes changes only equal-length explicit spellings")
    for path, new in PATHS:
        got = None if excluded(path) else rename_path(path)
        if got != new:
            bad.append("path %r -> %r, want %r" % (path, got, new))
    for line in bad:
        print("rename_niji: self-test FAIL " + line)
    print("rename_niji: self-test %s (%d examples, %d Rust examples, %d paths)"
          % ("FAIL" if bad else "PASS", len(EXAMPLES), len(RUST_EXAMPLES), len(PATHS)))
    return 1 if bad else 0


def main():
    if sys.argv[1:] == ["--self-test"]:
        return self_test()
    check = sys.argv[1:] == ["--check"]
    if sys.argv[1:] not in ([], ["--check"]):
        print(__doc__.strip().splitlines()[2].strip(), file=sys.stderr)
        return 2
    changed = []
    files = [p for p in tracked() if not excluded(p) and not os.path.islink(p) and os.path.isfile(p)]
    for path in files:
        with open(path, "rb") as f:
            data = f.read()
        text = as_text(path, data)
        if text is None:
            new = rename_bytes(data)
        elif stubs_owned(text):
            continue
        else:
            new = rename_text(text, path.endswith(".rs")).encode("utf-8")
        if new != data:
            changed.append(path)
            if not check:
                with open(path, "wb") as f:
                    f.write(new)
    moves = [(p, rename_path(p)) for p in files if rename_path(p) != p]
    for old, new in moves:
        changed.append(old + " -> " + new)
        if not check:
            os.makedirs(os.path.dirname(new) or ".", exist_ok=True)
            subprocess.run(["git", "mv", old, new], check=True)
    for line in changed:
        print(("would change: " if check else "changed: ") + line)
    print("rename_niji: %d change(s)" % len(changed))
    return 1 if check and changed else 0


if __name__ == "__main__":
    sys.exit(main())
