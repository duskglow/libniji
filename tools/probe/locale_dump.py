#!/usr/bin/env python3
"""LOCALE-PROBE-GEN: dump what the reference system's compiled locales say, as libniji's input
for the locale data CLDR lacks (owner ruling #7791: generated from black-box probes).

Run on a system with the reference's compiled locales installed (`locale -a`), no arguments;
writes the dump to stdout:

    python3 tools/probe/locale_dump.py > spec/locale-probe/locales.tsv
    cc -O2 -o fp tools/probe/locale_fingerprint.c
    python3 tools/probe/locale_dump.py --fingerprints ./fp > spec/locale-probe/fingerprints.tsv
    python3 tools/probe/locale_dump.py --ctype-diff ./fp > spec/locale-probe/ctype-diff.tsv

`--names <name>...` dumps those names instead of `locale -a`'s, and `LOCPATH` is passed on: so
the same `locale` program reads locales another localedef compiled (libniji's generated sources,
compiled into a directory), for a comparison with the dump.

For every name `locale -a` lists (sorted, so the output does not depend on its order), it runs
`LC_ALL=<name> locale charmap` and `LC_ALL=<name> locale -ck <categories>` (the reference's own
`locale` program: a black box) and writes one row per keyword:

    <locale name> TAB <category> TAB <keyword> TAB <value>

<value> is exactly the bytes `locale -k` printed after `=` (a string keeps its double quotes, a
number or byte list is bare), with every byte outside printable ASCII and the backslash written
as `\\xHH` (so `\\x5c` is a backslash): unambiguous whatever the locale's codeset is. The codeset
is the row `<name> TAB - TAB charmap TAB <codeset>`.

A name whose codeset is not UTF-8 and whose UTF-8 sibling (same language, territory and
modifier, codeset `.utf8`; without the modifier when there is none with it) gives the same text for a keyword (compared after decoding both with
Python's codec for the codeset) has the row `<name> TAB - TAB same-as TAB <sibling>` and only
its differing rows (the `*-codeset` rows always differ and are kept). A codeset without a codec
keeps every row.
"""
import codecs
import os
import re
import subprocess
import sys

CATEGORIES = ["LC_TELEPHONE", "LC_ADDRESS", "LC_NAME", "LC_PAPER", "LC_MEASUREMENT", "LC_IDENTIFICATION",
              "LC_NUMERIC", "LC_MONETARY", "LC_TIME", "LC_MESSAGES"]


def escape(b):
    return "".join(chr(c) if 0x20 <= c < 0x7f and c != 0x5c else "\\x%02x" % c for c in b)


def run(name, args):
    env = {"PATH": os.environ.get("PATH", "/usr/bin:/bin"), "LC_ALL": name}
    if "LOCPATH" in os.environ:
        env["LOCPATH"] = os.environ["LOCPATH"]
    r = subprocess.run(["locale"] + args, env=env, capture_output=True, timeout=60, check=False)
    if r.returncode != 0 or r.stderr:
        sys.exit("locale %s under %s: rc %d %r" % (" ".join(args), name, r.returncode, r.stderr[:200]))
    return r.stdout


def dump(name):
    charmap = run(name, ["charmap"]).strip().decode("ascii")
    rows, cat, skip = [], None, False
    for line in run(name, ["-ck"] + CATEGORIES).split(b"\n"):
        if line.decode("latin-1") in CATEGORIES:
            cat, skip = line.decode("ascii"), False
            continue
        k, eq, v = line.partition(b"=")
        if eq and re.fullmatch(rb"[a-z][a-z0-9_-]*", k):
            # time-era-entries is not a text item (the era entries are dumped through `era`):
            # what `locale -k` prints for it is left out, to the next keyword line.
            skip = k == b"time-era-entries"
            if not skip:
                rows.append((cat, k.decode("ascii"), v))
        elif not skip and line:
            sys.exit("%s: unexpected line %r" % (name, line))
    return charmap, rows


def same(v, charmap, utf8):
    """The same text: v in charmap, utf8 in UTF-8 (a byte either codec refuses: not the same)."""
    try:
        return v.decode(charmap) == utf8.decode("utf-8")
    except UnicodeDecodeError:
        return False


def sibling(name, data):
    """The UTF-8 name with the same modifier, else without it (`de_DE@euro`: `de_DE.utf8`)."""
    base, at, mod = name.partition("@")
    base = base.split(".")[0]
    with_mod = base + ".utf8" + at + mod
    return with_mod if with_mod in data else base + ".utf8"


def main(only=None):
    names = sorted(only or run("C", ["-a"]).decode("ascii").split())
    data = {n: dump(n) for n in names}
    host = subprocess.run(["dpkg-query", "-W", "-f", "${Package} ${Version}\\n", "libc6", "locales-all"],
                          capture_output=True, text=True, check=False).stdout.split("\n")
    out = sys.stdout
    out.write("# @generated by tools/probe/locale_dump.py (LOCALE-PROBE-GEN, owner ruling #7791); do not edit\n")
    out.write("# black-box probe of the reference's compiled locales: `locale -a`, `locale charmap`, `locale -ck`\n")
    out.write("# reference packages: %s\n" % "; ".join(h for h in host if h))
    out.write("# names: %d\n" % len(names))
    out.write("# name\tcategory\tkeyword\tvalue (bytes outside printable ASCII and \\ as \\xHH)\n")
    for n in names:
        charmap, rows = data[n]
        out.write("%s\t-\tcharmap\t%s\n" % (n, charmap))
        sib = sibling(n, data)
        keep = rows
        if charmap != "UTF-8" and sib in data and data[sib][0] == "UTF-8":
            try:
                codecs.lookup(charmap)
                ok = True
            except LookupError:
                ok = False
            if ok:
                theirs = {(c, k): v for c, k, v in data[sib][1]}
                out.write("%s\t-\tsame-as\t%s\n" % (n, sib))
                keep = [(c, k, v) for c, k, v in rows if (c, k) not in theirs or not same(v, charmap, theirs[(c, k)])]
                keep += [(c, k, b"<absent>") for (c, k) in theirs if (c, k) not in {(a, b) for a, b, _ in rows}]
        for c, k, v in keep:
            out.write("%s\t%s\t%s\t%s\n" % (n, c, k, escape(v)))


def fingerprints(binary):
    """Run tools/probe/locale_fingerprint.c's program over every name whose codeset is UTF-8."""
    names = [n for n in sorted(run("C", ["-a"]).decode("ascii").split()) if run(n, ["charmap"]).strip() == b"UTF-8"]
    out = sys.stdout
    out.write("# @generated by tools/probe/locale_dump.py --fingerprints (LOCALE-PROBE-GEN); do not edit\n")
    out.write("# black-box LC_CTYPE / LC_COLLATE behaviour of the reference's UTF-8 locales (tools/probe/locale_fingerprint.c)\n")
    for i in range(0, len(names), 16):
        r = subprocess.run([binary] + names[i:i + 16], capture_output=True, text=True, timeout=600, check=True)
        for line in r.stdout.splitlines():
            if line.endswith(" refused"):
                sys.exit(line)
            out.write(line + "\n")


def ctype_diff(binary):
    """`locale_fingerprint --diff en_US.utf8` over every UTF-8 name: the code points where a name's
    LC_CTYPE classes or case maps differ from en_US's (the generator's base, `copy "i18n"`)."""
    names = [n for n in sorted(run("C", ["-a"]).decode("ascii").split()) if run(n, ["charmap"]).strip() == b"UTF-8"]
    out = sys.stdout
    out.write("# @generated by tools/probe/locale_dump.py --ctype-diff (LOCALE-PROBE-GEN-2); do not edit\n")
    out.write("# black-box LC_CTYPE of the reference's UTF-8 locales where it differs from en_US.utf8's: name, item,\n")
    out.write("# +XXXX / -XXXX (in / not in the class) or XXXX>YYYY (the name's case mapping); no row = the same\n")
    host = subprocess.run(["dpkg-query", "-W", "-f", "${Package} ${Version}\\n", "libc6", "locales-all"],
                          capture_output=True, text=True, check=False).stdout.split("\n")
    out.write("# reference packages: %s; UTF-8 names: %d\n" % ("; ".join(h for h in host if h), len(names)))
    for i in range(0, len(names), 16):
        r = subprocess.run([binary, "--diff", "en_US.utf8"] + names[i:i + 16], capture_output=True, text=True, timeout=600, check=True)
        for line in r.stdout.splitlines():
            if line.endswith(" refused"):
                sys.exit(line)
            out.write(line + "\n")


if __name__ == "__main__":
    if sys.argv[1:2] == ["--fingerprints"]:
        fingerprints(sys.argv[2])
    elif sys.argv[1:2] == ["--ctype-diff"]:
        ctype_diff(sys.argv[2])
    elif sys.argv[1:2] == ["--names"]:
        main(sys.argv[2:])
    else:
        main()
