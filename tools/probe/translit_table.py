#!/usr/bin/env python3
"""LOCALE-TRANSLIT-TABLE: the reference's transliteration table, from a black-box probe (owner
ruling #7791: locale data by probe).

    cc -O2 -o tp tools/probe/translit_probe.c
    python3 tools/probe/translit_table.py ./tp spec/locale-probe/locales.tsv \
        > spec/locale-probe/translit.tsv 2> translit-report.txt

Under every legacy-codeset locale the probe dump lists (and en_US.utf8 for ASCII), iconv(3)
`<codeset>//TRANSLIT` of each code point the codeset lacks gives the first alternative of the
locale's table entry that the codeset encodes (`translit_probe first`). Each code point's
alternatives are then put in an order that gives every observed result first: an alternative
another codeset encodes comes after the one that codeset chose (a topological order; ties: the
alternative fewer codesets encode first, then code point order). The shared table holds a code
point when most of the locales lacking it give a result; per codeset the result most of its
locales give is used. A code point whose observations disagree (two locales of one codeset, or a
codeset that encodes an alternative yet gave nothing) is reported on stderr. A locale whose own
strings (its UTF-8 sibling's values) hold a code point its table treats otherwise than the shared
order gets its own row (`@<name>`).
"""
import collections
import subprocess
import sys
from concurrent.futures import ThreadPoolExecutor


def unescape(val):
    """A dump value's bytes (`\\xNN` escapes)."""
    out, i = bytearray(), 0
    while i < len(val):
        if val[i] == "\\" and val[i + 1 : i + 2] == "x":
            out.append(int(val[i + 2 : i + 4], 16))
            i += 4
        else:
            out += val[i].encode()
            i += 1
    return bytes(out)


def legacy_names(dump):
    """The legacy-codeset names (C and POSIX, ASCII, are not locales of a codeset), each with its
    codeset and the code points of its UTF-8 sibling's strings (what its own values hold)."""
    charmap, same, used = {}, {}, collections.defaultdict(set)
    header = []
    with open(dump, encoding="utf-8") as f:
        for line in f:
            if line.startswith("# reference packages"):
                header.append(line.rstrip("\n"))
            if line.startswith("#"):
                continue
            name, cat, kw, val = line.rstrip("\n").split("\t")
            if cat == "-" and kw == "charmap":
                charmap[name] = val
            elif cat == "-" and kw == "same-as":
                same[name] = val
            elif len(val) >= 2 and val[0] == '"' and val[-1] == '"':
                b = unescape(val[1:-1])
                try:
                    used[name] |= {ord(ch) for ch in b.decode("utf-8")}
                except UnicodeDecodeError:
                    pass
    names = sorted((n, c, used.get(same.get(n, ""), set())) for n, c in charmap.items() if c not in ("UTF-8", "ANSI_X3.4-1968"))
    return names + [("en_US.utf8", "ANSI_X3.4-1968", set())], header


def first(tp, name, cs):
    out = subprocess.run([tp, "first", name, cs], capture_output=True, text=True, check=False, timeout=900)
    if out.returncode != 0:
        return name, cs, None, {}
    lines = out.stdout.splitlines()
    default = lines[0].split("\t")[1]
    res = {}
    for line in lines[1:]:
        cp, r = line.split("\t")
        if r and r != "unreadable":
            res[int(cp, 16)] = r
    return name, cs, default, res


def enc(tp, codesets, strings):
    text = "".join(s + "\n" for s in strings)
    out = subprocess.run([tp, "enc", *codesets], input=text, capture_output=True, text=True, check=True, timeout=900)
    return dict(zip(strings, out.stdout.splitlines()))


def main():
    tp, dump = sys.argv[1], sys.argv[2]
    names, header = legacy_names(dump)
    with ThreadPoolExecutor(max_workers=16) as ex:
        runs = list(ex.map(lambda t: first(tp, t[0], t[1]), names))
    used = {n: u for n, _, u in names}
    log = sys.stderr
    for name, cs, default, _ in runs:
        if default is None:
            print(f"refused {name} {cs}", file=log)
        elif default != "3F":
            print(f"default_missing {name} {cs}: {default}", file=log)
    runs = [r for r in runs if r[2] is not None]
    codesets = sorted({cs for _, cs, _, _ in runs})
    cps = sorted({cp for *_, res in runs for cp in res})
    lacks = enc(tp, codesets, [f"{cp:04X}" for cp in cps])
    results = sorted({r for *_, res in runs for r in res.values()})
    fits = enc(tp, codesets, results)
    col = {cs: i for i, cs in enumerate(codesets)}

    print("# @generated by tools/probe/translit_table.py (LOCALE-TRANSLIT-TABLE, owner ruling #7791); do not edit")
    print("# black-box probe: iconv(3) <codeset>//TRANSLIT of each code point under each legacy-codeset locale of")
    print("# the reference (and en_US.utf8 for ANSI_X3.4-1968); tools/probe/translit_probe.c")
    for h in header:
        print(h)
    print(f"# {len(runs)} locales, codesets: {' '.join(codesets)}")
    print("# <code point>\t<alternatives in the order they are tried, ';'-separated; each one space-separated code points>")
    shared = {}
    for cp in cps:
        # Per codeset: which result each locale of that codeset gave (None: nothing).
        seen = collections.defaultdict(collections.Counter)
        for name, cs, _, res in runs:
            if lacks[f"{cp:04X}"][col[cs]] == "0":
                seen[cs][res.get(cp)] += 1
        # The shared table holds an entry most locales lacking the code point have; a locale
        # that differs gets its own entry below when its strings hold the code point.
        some = sum(n for cnt in seen.values() for r, n in cnt.items() if r)
        none = sum(n for cnt in seen.values() for r, n in cnt.items() if not r)
        if none >= some:
            continue
        chosen = {}
        for cs, cnt in seen.items():
            top = sorted(cnt.items(), key=lambda kv: (kv[0] is None, -kv[1], kv[0] or ""))
            if len(cnt) > 1:
                print(f"conflict U+{cp:04X} {cs}: " + ", ".join(f"{r or '-'} x{n}" for r, n in top), file=log)
            chosen[cs] = top[0][0]
        alts = sorted({r for r in chosen.values() if r})
        after = {r: set() for r in alts}
        for cs, r in chosen.items():
            fitting = [a for a in alts if fits[a][col[cs]] == "1"]
            if r is None:
                if fitting:
                    print(f"inconsistent U+{cp:04X} {cs}: nothing, yet {fitting} fit", file=log)
                continue
            for a in fitting:
                if a != r:
                    after[r].add(a)
        before = {r: {a for a in alts if r in after[a]} for r in alts}
        key = lambda a: (fits[a].count("1"), a)
        order = []
        left = set(alts)
        while left:
            ready = [a for a in left if not (before[a] & left)]
            if not ready:
                print(f"cycle U+{cp:04X}: {sorted(left)}", file=log)
                ready = list(left)
            a = min(ready, key=key)
            order.append(a)
            left.remove(a)
        if order:
            shared[cp] = order
            print(f"{cp:04X}\t{';'.join(order)}")

    # A locale whose own strings hold a code point its table treats differently from the shared
    # order (its result in its codeset, or nothing): that locale's own entry.
    print("# per locale, for the code points its own strings hold: @<name>\t<code point>\t<its result, or - for none>")
    # Over every code point (not only a locale's own strings): how far the shared table is from
    # each locale's (what iconv //TRANSLIT gives in its codeset), for the report.
    off = collections.Counter()
    for name, cs, _, res in runs:
        for cp in cps:
            if lacks[f"{cp:04X}"][col[cs]] == "0" and res.get(cp) != next((a for a in shared.get(cp, []) if fits[a][col[cs]] == "1"), None):
                off[name] += 1
    print(f"summary: {len(shared)} shared entries; {sum(off.values())} (locale, code point) pairs differ from the shared table in {len(off)} of {len(runs)} locales", file=log)
    for name, n in off.most_common():
        print(f"off {name} {n}", file=log)
    for name, cs, _, res in runs:
        for cp in sorted(used[name] & set(cps)):
            if lacks[f"{cp:04X}"][col[cs]] == "1":
                continue
            want = res.get(cp)
            got = next((a for a in shared.get(cp, []) if fits[a][col[cs]] == "1"), None)
            if want != got:
                print(f"@{name}\t{cp:04X}\t{want or '-'}")


if __name__ == "__main__":
    main()
