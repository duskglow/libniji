#!/usr/bin/env python3
"""The reference library's variant of an East Asian multi-byte charset, as data (ICONV-CJK).

usage: iconv_variant.py CHARSET DUMP PUBLIC FORMAT [AMBIG] > spec/encoding/reference/<CHARSET>.tsv

DUMP is the output of crates/core/tests/oracle/iconv_codespace.c for CHARSET run against the
reference C library (a black-box probe). PUBLIC is the public mapping table the built-in codec
is generated from; FORMAT is `unicode` (Unicode Consortium format: 0xCODE<TAB>0xUCS) or `gb18030`
(the WHATWG Encoding Standard's index-gb18030.txt; its sibling index-gb18030-ranges.txt is read
for the four-byte sequences). AMBIG (optional) holds lines `CHARSET <hex> <cp>... r=.. left=..`
of an //IGNORE decode of an invalid two-byte sequence followed by a byte that completes a
character with its trail byte: it settles skips the code-space dump cannot tell apart.

The output lists only what the public table does not say, so `cargo xtask encodings-gen` can
build the reference's variant from the public table plus this file (format in
spec/encoding/reference/README.md). Python 3 standard library only.
"""
import os
import sys


def ranges(xs):
    xs, out, i = sorted(xs), [], 0
    while i < len(xs):
        j = i
        while j + 1 < len(xs) and xs[j + 1] == xs[j] + 1:
            j += 1
        out.append(f'{xs[i]:02X}' + (f'-{xs[j]:02X}' if j > i else ''))
        i = j + 1
    return ','.join(out) or '-'


def main():
    cs, dump, public, fmt = sys.argv[1:5]
    ambig = sys.argv[5] if len(sys.argv) > 5 else None
    gb = fmt == 'gb18030'
    four_ranges = []
    if gb:
        for line in open(os.path.join(os.path.dirname(public), 'index-gb18030-ranges.txt')):
            if line.strip() and not line.startswith('#'):
                p, c = line.split()[:2]
                four_ranges.append((int(p), int(c, 16)))

    def four_public(ptr):
        if 189000 <= ptr <= 1237575:
            return 0x10000 + ptr - 189000
        if ptr > 39419:
            return None
        base = max((r for r in four_ranges if r[0] <= ptr), default=None)
        return None if base is None else base[1] + ptr - base[0]

    one, two, four, inval, enc = {}, {}, {}, {}, {}
    for line in open(dump):
        f = line.split()
        if f[0] == 'D':
            s = bytes.fromhex(f[1])
            cp = int(f[2], 16)
            if len(s) == 1:
                one[s[0]] = cp
            elif len(s) == 2:
                two[s] = cp
            else:
                four[s] = cp
        elif f[0] == 'I' and len(f[1]) == 4:
            inval[bytes.fromhex(f[1])] = None
        elif f[0] == 'G' and len(f[1]) == 4:
            inval[bytes.fromhex(f[1])] = [int(x, 16) for x in f[2:-3]]
        elif f[0] == 'E':
            enc[int(f[1], 16)] = bytes.fromhex(f[2]) if len(f) > 2 else b''
    leads = sorted({s[0] for s in list(two) + list(inval)})
    trails = sorted({s[1] for s in two})
    assert all(one.get(b) == b for b in range(0x80)), 'ASCII is not itself'

    pub = {}
    for line in open(public, encoding='latin-1'):
        if line.startswith('#') or not line.strip():
            continue
        f = line.split()
        if fmt == 'unicode':
            if len(f) < 2 or not f[1].startswith('0x'):
                continue
            code, cp = int(f[0], 16), int(f[1], 16)
        else:
            p, cp = int(f[0]), int(f[1], 16)
            lead, t = divmod(p, 190)
            code = (lead + 0x81) << 8 | (t + (0x40 if t < 0x3F else 0x41))
        if code > 0xFF and code >> 8 in leads and code & 0xFF in trails:
            pub[code] = cp
    print(f'# The reference library\'s {cs}, beyond {os.path.basename(public)}: generated by')
    print(f'# tools/probe/iconv_variant.py from a black-box probe (iconv_codespace.c); format in README.md.')
    print(f'leads\t{ranges(leads)}')
    print(f'trails\t{ranges(trails)}')
    singles = sorted(b for b in one if b >= 0x80)
    k = 0
    while k < len(singles):
        j = k
        while j + 1 < len(singles) and singles[j + 1] == singles[j] + 1 and one[singles[j + 1]] == one[singles[j]] + 1:
            j += 1
        print(f'single\t{singles[k]:02X}\t{singles[j]:02X}\t{one[singles[k]]:04X}')
        k = j + 1

    # cells in the set's cell order (lead, then trail in `trails` order)
    order = [(lead << 8 | t) for lead in leads for t in trails]
    ref = {int.from_bytes(s, 'big'): cp for s, cp in two.items()}
    changed = [c for c in order if ref.get(c) != pub.get(c)]
    pos = {c: i for i, c in enumerate(order)}
    k = 0
    while k < len(changed):
        c0 = changed[k]
        v0 = ref.get(c0)
        j = k
        while j + 1 < len(changed):
            c1 = changed[j + 1]
            if pos[c1] != pos[changed[j]] + 1:
                break
            if v0 is None and ref.get(c1) is not None:
                break
            if v0 is not None and ref.get(c1) != v0 + (j + 1 - k):
                break
            j += 1
        print(f'cells\t{c0:04X}\t{changed[j]:04X}\t' + ('none' if v0 is None else f'{v0:04X}'))
        k = j + 1

    # the codes of each code point in the final decode table: default encoding = shortest, then lowest
    codes = {}
    for b, cp in one.items():
        codes.setdefault(cp, []).append(bytes([b]))
    for s, cp in sorted(two.items()):
        codes.setdefault(cp, []).append(s)
    four_dev = []
    if gb:
        for s, cp in sorted(four.items()):
            b1, b2, b3, b4 = s
            ptr = ((b1 - 0x81) * 10 + b2 - 0x30) * 1260 + (b3 - 0x81) * 10 + b4 - 0x30
            if cp != four_public(ptr):
                four_dev.append((ptr, cp))
            codes.setdefault(cp, []).append(s)
        for ptr, cp in four_dev:
            print(f'four\t{ptr}\t{cp:04X}')
    for cp in sorted(set(enc) | set(codes)):
        cands = sorted(codes.get(cp, []), key=lambda s: (len(s), s))
        want = enc.get(cp)
        have = cands[0] if cands else None
        if want == have or 0xE0000 <= cp <= 0xE007F and want == b'':
            continue
        print(f'encode\t{cp:04X}\t' + ('none' if want is None else want.hex().upper() or 'empty'))

    # //IGNORE: how far an invalid two-byte sequence is skipped (1 or 2 bytes) after each lead
    amb = {}
    if ambig:
        for line in open(ambig):
            f = line.split()
            if f[0] == cs:
                s = bytes.fromhex(f[1])
                amb[s[:2]] = (s, [int(x, 16) for x in f[2:-2]])
    skip1 = {}
    for s, out in inval.items():
        if out is None:
            continue
        t = s[1]
        if t in one:
            k = 1 if out == [one[t], 0x41] else 2
        elif s in amb:
            seq, got = amb[s]
            k = 1 if got[:1] == [two.get(seq[1:3])] else 2
        elif bytes([t, 0x41]) in two:
            k = 1 if out == [two[bytes([t, 0x41])]] else 2
        else:
            k = 2  # indistinguishable by any continuation: the skip of the trail byte's own error is the same
        if k == 1:
            skip1.setdefault(s[0], []).append(t)
    sig = {}
    for lead in leads:
        sig.setdefault(ranges(skip1.get(lead, [])), []).append(lead)
    for trails_1, ls in sig.items():
        print(f'skip1\t{ranges(ls)}\t{trails_1}')
    ign = {line.split()[-3] for line in open(dump) if line.startswith('G ')}
    print(f'ignore-result\t{"error" if ign == {"r=-1"} else "success" if ign == {"r=0"} else ",".join(sorted(ign))}')


main()
