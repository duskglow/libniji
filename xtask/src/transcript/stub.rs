//! Liella's side of the `ldconfig` transcripts until UTIL-3 builds the real command: `ldconfig -p [-C CACHE]` only,
//! reading the cache with the loader's reader (`liella_ld::cache`, D-27.16). This binary runs it when started with
//! argv[0] `ldconfig` (the transcript runner does that). Everything else is refused with exit 2, so a transcript that
//! needs more fails loudly instead of comparing against a guess.

use std::ffi::OsString;
use std::io::Write;
use std::os::unix::ffi::OsStrExt;
use std::process::ExitCode;

/// The cache a plain `-p` reads (spec §31.2, Appendix D.3).
const DEFAULT_CACHE: &str = "/etc/ld.so.cache";

/// The text `-p` prints for an entry's flags word (spec §31.2 Guarantees, probe `ldconfig-p`; the other words from
/// the UTIL-HARNESS transcripts of the reference).
fn flags_text(flags: u32) -> Option<&'static str> {
    // Only the words validation/transcripts/ldconfig/p-flags.transcript recorded; any other is refused.
    Some(match flags {
        0x0000 | 0x0001 | 0x0002 | 0x0004 | 0x00ff => "unknown or unsupported flag",
        0x0003 => "libc6",
        0x0103 | 0x0403 | 0x0503 | 0x0703 => "libc6,64bit",
        0x0203 => "libc6,512",
        0x0303 => "libc6,x86-64",
        0x0603 => "libc6,N32",
        0x0803 => "libc6,x32",
        0x0903 => "libc6,hard-float",
        0x0a03 => "libc6,AArch64",
        0x0b03 | 0x0f03 => "libc6,soft-float",
        0x1303 => "libc6,4864",
        _ => return None,
    })
}

/// `ldconfig` as the transcript stub. `argv0` is the program name used in messages.
pub(crate) fn ldconfig(argv0: &OsString, args: &[OsString]) -> ExitCode {
    let me = String::from_utf8_lossy(argv0.as_bytes()).into_owned();
    let refuse = |what: &str| {
        eprintln!("{me}: Liella transcript stub: {what}; only -p [-C CACHE] until UTIL-3");
        ExitCode::from(2)
    };
    let mut print = false;
    let mut cache: OsString = DEFAULT_CACHE.into();
    let mut i = 0;
    while i < args.len() {
        let a = args[i].as_bytes();
        match a {
            b"-p" | b"--print-cache" => print = true,
            b"-C" => match args.get(i + 1) {
                Some(c) => {
                    cache = c.clone();
                    i += 1;
                }
                None => return refuse("-C without a file"),
            },
            _ if a.starts_with(b"-C") => cache = OsString::from(std::ffi::OsStr::from_bytes(&a[2..])),
            _ => return refuse(&format!("option {:?}", String::from_utf8_lossy(a))),
        }
        i += 1;
    }
    if !print {
        return refuse("no -p");
    }
    let name = String::from_utf8_lossy(cache.as_bytes()).into_owned();
    let bytes = match std::fs::read(&cache) {
        Ok(b) => b,
        Err(e) => {
            // The message and the error text on the next line (spec §31.2 Failure, probe `ldconfig-p-missing`).
            let text = e.to_string();
            let text = text.split(" (os error").next().unwrap_or_default();
            eprintln!("{me}: Can't open cache file {name}\n: {text}");
            return ExitCode::from(1);
        }
    };
    let Some(c) = liella_ld::cache::Cache::parse(&bytes) else { return refuse(&format!("{name} is not a cache the reader accepts")) };
    let mut out = Vec::new();
    let _ = writeln!(out, "{} libs found in cache `{name}'", c.len());
    for i in 0..c.len() {
        let Some(e) = c.get(i) else { return refuse(&format!("entry {i} is inconsistent")) };
        let Some(flags) = flags_text(e.flags) else { return refuse(&format!("flags 0x{:x} (no probe of their text yet)", e.flags)) };
        out.push(b'\t');
        out.extend_from_slice(e.key);
        let _ = write!(out, " ({flags}");
        if let Some(h) = e.hwcaps {
            out.extend_from_slice(b", hwcap: \"");
            out.extend_from_slice(h);
            out.push(b'"');
        }
        out.extend_from_slice(b") => ");
        out.extend_from_slice(e.path);
        out.push(b'\n');
    }
    if let Some(g) = c.generator() {
        out.extend_from_slice(b"Cache generated by: ");
        out.extend_from_slice(g);
        out.push(b'\n');
    }
    match std::io::stdout().write_all(&out) {
        Ok(()) => ExitCode::SUCCESS,
        Err(_) => ExitCode::from(1),
    }
}
