//! The generated charmaps (SYS-ICONV-COVERAGE; D-6.8's format, data from public mapping tables):
//! `cargo xtask so` writes one POSIX charmap per row of `spec/encoding/charmaps.tsv` into
//! `target/niji/charmaps/<name>`, which the system packages install as
//! `/usr/share/i18n/charmaps/<name>` (`tools/deb/system.sh`), where `iconv_open` reads them.
//!
//! Each row names a single-byte Unicode mapping file under `spec/encoding/unicode` (vendored
//! unchanged; README.md there), whether the control codes the file leaves out map to themselves,
//! and the other names the charset answers to (`% alias` lines). The mapping lines are the file's
//! own, in byte order; nothing is taken from another C library's data.

use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::fs;
use std::path::Path;

const TABLE: &str = "spec/encoding/charmaps.tsv";
const SOURCES: &str = "spec/encoding/unicode";

/// The byte-to-code-point pairs of the Unicode mapping file `src` (format A: `0xBB<TAB>0xUUUU`,
/// `#` comments; a byte with no code point is unmapped).
fn mapping(root: &Path, src: &str) -> Result<BTreeMap<u8, u32>, String> {
    let path = root.join(SOURCES).join(src);
    let text = fs::read(&path).map_err(|e| format!("{}: {e}", path.display()))?;
    let mut out = BTreeMap::new();
    for (k, line) in String::from_utf8_lossy(&text).lines().enumerate() {
        let line = line.split('#').next().unwrap_or("").trim();
        if line.is_empty() {
            continue;
        }
        let bad = |what: &str| format!("{src}:{}: {what}", k + 1);
        let mut f = line.split_whitespace();
        let b = f.next().and_then(|s| s.strip_prefix("0x")).ok_or_else(|| bad("not `0xBB 0xUUUU`"))?;
        let b = u8::from_str_radix(b, 16).map_err(|_| bad("not a single byte"))?;
        let Some(cp) = f.next() else { continue };
        let cp = cp.strip_prefix("0x").ok_or_else(|| bad("code point not `0xUUUU` (sequences are not supported)"))?;
        let cp = u32::from_str_radix(cp, 16).map_err(|_| bad("code point not `0xUUUU` (sequences are not supported)"))?;
        if cp > 0x10_FFFF || (0xD800..0xE000).contains(&cp) {
            return Err(bad("not a Unicode scalar value"));
        }
        if out.insert(b, cp).is_some() {
            return Err(bad("byte listed twice"));
        }
    }
    Ok(out)
}

/// The charmap text of one table row.
fn charmap(root: &Path, name: &str, src: &str, controls: &str, aliases: &str) -> Result<String, String> {
    let mut map = mapping(root, src)?;
    match controls {
        "as-is" => {}
        "fill" => {
            for b in (0..0x20).chain([0x7F]) {
                map.entry(b).or_insert(u32::from(b));
            }
        }
        o => return Err(format!("{TABLE}: {name}: controls `{o}`: as-is or fill")),
    }
    let mut t = String::new();
    let _ = writeln!(t, "<code_set_name> {name}\n<comment_char> %\n<escape_char> /\n<mb_cur_min> 1\n<mb_cur_max> 1");
    let _ = writeln!(t, "% Generated by `cargo xtask so` (xtask/src/charmaps.rs) from the Unicode mapping file\n% {src} (spec/encoding/unicode/README.md).");
    for a in aliases.split_whitespace() {
        let _ = writeln!(t, "% alias {a}");
    }
    t.push_str("CHARMAP\n");
    for (b, cp) in &map {
        let _ = writeln!(t, "<U{cp:04X}> /x{b:02x}");
    }
    t.push_str("END CHARMAP\n");
    Ok(t)
}

/// Write every charmap of the table into `out` (replacing what is there); returns how many.
pub fn write(root: &Path, out: &Path) -> Result<usize, String> {
    let table = fs::read_to_string(root.join(TABLE)).map_err(|e| format!("{TABLE}: {e}"))?;
    let mut files = BTreeMap::new();
    for (k, line) in table.lines().enumerate().filter(|(_, l)| !l.starts_with('#')).skip(1) {
        let f: Vec<&str> = line.split('\t').collect();
        let [name, src, controls, aliases] = f[..] else {
            return Err(format!("{TABLE}:{}: want name, source, controls, aliases", k + 1));
        };
        if name.is_empty() || name.contains('/') || name.starts_with('.') {
            return Err(format!("{TABLE}:{}: `{name}` is not a file name", k + 1));
        }
        if files.insert(name.to_string(), charmap(root, name, src, controls, aliases)?).is_some() {
            return Err(format!("{TABLE}:{}: {name} listed twice", k + 1));
        }
    }
    if out.exists() {
        fs::remove_dir_all(out).map_err(|e| format!("{}: {e}", out.display()))?;
    }
    fs::create_dir_all(out).map_err(|e| format!("{}: {e}", out.display()))?;
    for (name, text) in &files {
        fs::write(out.join(name), text).map_err(|e| format!("{}/{name}: {e}", out.display()))?;
    }
    Ok(files.len())
}
