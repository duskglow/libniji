//! `spec/abi/PROVENANCE`, rendered from one fragment per story plus counts taken from the tables (D-X.172).
//!
//! Each story that regenerated or hand-edited a `spec/abi` table used to append a paragraph to the one hand-kept
//! `spec/abi/PROVENANCE`, so two header stories always edited the same last lines and conflicted in CI. A
//! paragraph is now its own file, `spec/abi/provenance.d/<STORY-ID>.txt`:
//!
//! ```text
//! ---
//! order: 210
//! ---
//! visibility.tsv (MY-STORY): how the rows were made, on which system, which rows changed.
//! ```
//!
//! `order` places the paragraph in the history (ties by file name), so the history reads in the order the
//! paragraphs were written without anyone editing a shared list. The counts of the current tables (rows, types,
//! headers, names) are not written by hand at all: `render` counts them, so a story that changes a table never edits
//! a count either. `spec/abi/PROVENANCE` itself is a generated view: `cargo xtask records-gen` renders it with the
//! decision tables (train-owned, D-X.55 / D-X.59; off the train it writes `target/records-views/spec/abi/PROVENANCE`),
//! and the static check `records-gen` names it when it is stale (fatal on the train). A malformed fragment is an
//! error everywhere. Format and workflow: `spec/abi/provenance.d/README.md`.

use std::collections::BTreeSet;
use std::fs;
use std::path::Path;

/// The view, relative to the workspace root.
pub(crate) const VIEW: &str = "spec/abi/PROVENANCE";
/// The fragment directory, relative to the workspace root.
pub(crate) const DIR: &str = "spec/abi/provenance.d";
/// The tables directory.
const ABI: &str = "spec/abi";
/// Files of [`DIR`] that are not fragments.
const NOT_FRAGMENTS: &[&str] = &["README.md"];
/// The first line of the view.
pub(crate) const GENERATED: &str = "@generated by `cargo xtask records-gen` from spec/abi/provenance.d/ and the spec/abi tables: add a fragment there, never edit this file";

/// A table the summary counts: its file, the noun of its rows, and the columns whose distinct values are counted too
/// (column, noun).
type Counted = (&'static str, &'static str, &'static [(&'static str, &'static str)]);

/// The tables of the summary, in the order it lists them, with what each count means.
const TABLES: &[Counted] = &[
    ("layouts.tsv", "rows", &[("type", "types")]),
    ("initializers.tsv", "rows", &[]),
    ("enumerators.tsv", "rows", &[("tag", "tags")]),
    ("enum-macros.tsv", "rows", &[]),
    ("prototypes.tsv", "rows", &[("header", "headers")]),
    ("chk-prototypes.tsv", "rows", &[]),
    ("constants.tsv", "rows", &[]),
    ("macros.tsv", "rows", &[("header", "headers")]),
    ("typedefs.tsv", "rows", &[("header", "headers")]),
    ("versions.tsv", "versioned symbol rows", &[("library", "libraries"), ("version", "version nodes")]),
    ("empty-versions.tsv", "version definitions no exported symbol carries", &[]),
    ("libm-ulps.tsv", "rows", &[("function", "functions")]),
    ("ftm-configs.tsv", "configurations", &[]),
    ("visibility.tsv", "rows", &[("header", "headers"), ("name", "names")]),
    ("callsites.tsv", "call-site rows", &[("name", "functions")]),
    ("noexcept.tsv", "rows", &[]),
    ("diagattrs.tsv", "functions", &[]),
    ("typegeneric.tsv", "rows", &[("header", "headers"), ("config", "configurations")]),
];

#[derive(Debug, Clone, PartialEq, Eq)]
pub(crate) struct Fragment {
    /// The file name (`HEADERS-TABLES-NET.txt`), the tie-break of `order`.
    pub name: String,
    /// The sort key of the front matter.
    pub order: u32,
    /// The paragraph, no trailing newline.
    pub body: String,
}

/// A fragment file name: a story id (`[A-Z0-9][A-Z0-9-]*`) and `.txt`.
fn valid_name(name: &str) -> bool {
    let Some(stem) = name.strip_suffix(".txt") else { return false };
    let mut ch = stem.chars();
    matches!(ch.next(), Some(c) if c.is_ascii_uppercase() || c.is_ascii_digit())
        && ch.all(|c| c.is_ascii_uppercase() || c.is_ascii_digit() || c == '-')
}

/// Parse one fragment; the error names the file and the rule it breaks.
pub(crate) fn parse_fragment(name: &str, text: &str) -> Result<Fragment, String> {
    let err = |what: &str| Err(format!("{DIR}/{name}: {what}"));
    if !valid_name(name) {
        return err("the file name is not <STORY-ID>.txt (capitals, digits and '-')");
    }
    if text.contains('\r') {
        return err("carriage return (the repository is LF)");
    }
    if !text.ends_with('\n') {
        return err("no newline at the end of the file");
    }
    let mut lines = text.lines();
    if lines.next() != Some("---") {
        return err("does not start with the front matter line `---`");
    }
    let Some(order) = lines.next().and_then(|l| l.strip_prefix("order: ")).and_then(|v| v.parse::<u32>().ok()) else {
        return err("the second line is not `order: <number>`");
    };
    if lines.next() != Some("---") {
        return err("the front matter is not closed by `---` on its third line");
    }
    let body: Vec<&str> = lines.collect();
    if body.is_empty() || body.iter().any(|l| l.trim().is_empty()) {
        return err("the paragraph is empty or has a blank line (one paragraph per fragment)");
    }
    if body.iter().any(|l| l.ends_with(' ') || l.ends_with('\t')) {
        return err("trailing white space");
    }
    Ok(Fragment { name: name.to_string(), order, body: body.join("\n") })
}

/// Every fragment of `<root>/DIR`, sorted by (order, file name); all problems at once.
pub(crate) fn fragments(root: &Path) -> Result<Vec<Fragment>, String> {
    let dir = root.join(DIR);
    let rd = fs::read_dir(&dir).map_err(|e| format!("{DIR}: {e}"))?;
    let mut names = Vec::new();
    for e in rd {
        let e = e.map_err(|e| format!("{DIR}: {e}"))?;
        names.push(e.file_name().to_string_lossy().into_owned());
    }
    // Listing order is the file system's; sort before use (no file-system dependence).
    names.sort();
    let (mut out, mut bad) = (Vec::new(), Vec::new());
    for n in names.iter().filter(|n| !NOT_FRAGMENTS.contains(&n.as_str())) {
        let text = fs::read_to_string(dir.join(n)).map_err(|e| format!("{DIR}/{n}: {e}"))?;
        match parse_fragment(n, &text) {
            Ok(f) => out.push(f),
            Err(e) => bad.push(e),
        }
    }
    if !bad.is_empty() {
        return Err(bad.join("\n"));
    }
    if out.is_empty() {
        return Err(format!("{DIR}: no fragment"));
    }
    out.sort_by(|a, b| (a.order, &a.name).cmp(&(b.order, &b.name)));
    Ok(out)
}

/// The summary line of one table: `<file>: <rows> <noun>, <distinct> <noun>, ...`. `#` lines are comments; the first
/// other line names the columns.
fn count_line(file: &str, text: &str, noun: &str, distinct: &[(&str, &str)]) -> Result<String, String> {
    let mut lines = text.lines().filter(|l| !l.starts_with('#'));
    let head: Vec<&str> = lines.next().ok_or_else(|| format!("{ABI}/{file}: no header line"))?.split('\t').collect();
    let mut cols = Vec::new();
    for (c, _) in distinct {
        cols.push(head.iter().position(|h| h == c).ok_or_else(|| format!("{ABI}/{file}: no column `{c}`"))?);
    }
    let mut sets: Vec<BTreeSet<&str>> = vec![BTreeSet::new(); cols.len()];
    let mut rows = 0usize;
    for l in lines.filter(|l| !l.is_empty()) {
        rows += 1;
        let cells: Vec<&str> = l.split('\t').collect();
        for (s, &i) in sets.iter_mut().zip(&cols) {
            s.insert(cells.get(i).copied().unwrap_or(""));
        }
    }
    let mut line = format!("{file}: {rows} {noun}");
    for (s, (_, n)) in sets.iter().zip(distinct) {
        line.push_str(&format!(", {} {n}", s.len()));
    }
    Ok(line)
}

/// The view's text: the counts of the current tables, then the fragments in order.
pub(crate) fn render(root: &Path) -> Result<String, String> {
    let frags = fragments(root)?;
    let mut t = format!("{GENERATED}\n");
    t.push_str("Current tables, counted from spec/abi by `cargo xtask records-gen` (no count here is written by hand):\n");
    for (file, noun, distinct) in TABLES {
        let text = fs::read_to_string(root.join(ABI).join(file)).map_err(|e| format!("{ABI}/{file}: {e}"))?;
        t.push_str(&count_line(file, &text, noun, distinct)?);
        t.push('\n');
    }
    t.push_str("\nHistory: one paragraph per story, spec/abi/provenance.d/<STORY-ID>.txt in `order`; a count in a paragraph is what that run gave.\n");
    for f in &frags {
        t.push_str(&f.body);
        t.push('\n');
    }
    Ok(t)
}

/// The (path, text) the records views gain: the view when the tree has it or its fragments (a scratch tree of the
/// records tests has neither); the fragment directory missing beside a view is an error, never a silent skip.
pub(crate) fn rendered_view(root: &Path) -> Result<Option<(String, String)>, String> {
    let (has_dir, has_view) = (root.join(DIR).is_dir(), root.join(VIEW).is_file());
    match (has_dir, has_view) {
        (false, false) => Ok(None),
        (false, true) => Err(format!("{VIEW} exists but {DIR}/ does not: the view is rendered from its fragments")),
        _ => Ok(Some((VIEW.to_string(), render(root)?))),
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::path::PathBuf;

    fn tmp(tag: &str) -> PathBuf {
        let d = std::env::temp_dir().join(format!("xtask-provenance-{tag}-{}", std::process::id()));
        let _ = fs::remove_dir_all(&d);
        fs::create_dir_all(d.join(DIR)).unwrap();
        for (file, _, distinct) in TABLES {
            let mut head: Vec<&str> = vec!["x"];
            head.extend(distinct.iter().map(|(c, _)| *c));
            fs::write(d.join(ABI).join(file), format!("{}\n", head.join("\t"))).unwrap();
        }
        d
    }

    /// D-X.172 (no spec clause): the view's counts follow the tables: a row added to a table changes the count the
    /// view states, with no fragment touched (a story never edits a count by hand).
    #[test]
    fn counts_follow_the_tables() {
        let d = tmp("counts");
        fs::write(d.join(DIR).join("A.txt"), "---\norder: 10\n---\nfirst\n").unwrap();
        fs::write(d.join(ABI).join("layouts.tsv"), "x\ttype\n1\tstruct a\n2\tstruct a\n3\tstruct b\n").unwrap();
        let v = render(&d).unwrap();
        assert!(v.contains("\nlayouts.tsv: 3 rows, 2 types\n"), "{v}");
        fs::write(d.join(ABI).join("layouts.tsv"), "# comment\nx\ttype\n1\tstruct a\n2\tstruct a\n3\tstruct b\n4\tstruct c\n").unwrap();
        let w = render(&d).unwrap();
        assert!(w.contains("\nlayouts.tsv: 4 rows, 3 types\n"), "{w}");
        assert!(w.starts_with(GENERATED) && w.ends_with("\nfirst\n"), "{w}");
        let _ = fs::remove_dir_all(&d);
    }

    /// D-X.172 (no spec clause): the history is ordered by `order`, then by file name, whatever order the files were
    /// written or listed in, and each fragment's text is kept as written.
    #[test]
    fn history_orders_by_key_then_name() {
        let d = tmp("order");
        for (n, o, b) in [("ZED.txt", 10, "z para"), ("B.txt", 20, "b para\nline two"), ("A.txt", 20, "a para"), ("C.txt", 5, "c para")] {
            fs::write(d.join(DIR).join(n), format!("---\norder: {o}\n---\n{b}\n")).unwrap();
        }
        fs::write(d.join(DIR).join("README.md"), "not a fragment\n").unwrap();
        let v = render(&d).unwrap();
        let hist = v.split_once("\nHistory:").unwrap().1;
        let hist = hist.split_once('\n').unwrap().1;
        assert_eq!(hist, "c para\nz para\na para\nb para\nline two\n");
        let _ = fs::remove_dir_all(&d);
    }

    /// D-X.172 (no spec clause): a malformed fragment is rejected with its file named, so it never renders silently
    /// wrong.
    #[test]
    fn malformed_fragments_are_rejected() {
        for (name, text) in [
            ("lower.txt", "---\norder: 1\n---\nx\n"),
            ("A.md", "---\norder: 1\n---\nx\n"),
            ("A.txt", "order: 1\n---\nx\n"),
            ("A.txt", "---\norder: one\n---\nx\n"),
            ("A.txt", "---\norder: 1\nx\n"),
            ("A.txt", "---\norder: 1\n---\n"),
            ("A.txt", "---\norder: 1\n---\nx\n\ny\n"),
            ("A.txt", "---\norder: 1\n---\nx \n"),
            ("A.txt", "---\norder: 1\n---\nx"),
            ("A.txt", "---\r\norder: 1\n---\nx\n"),
        ] {
            let e = parse_fragment(name, text).expect_err(text);
            assert!(e.starts_with(&format!("{DIR}/{name}: ")), "{e}");
        }
        assert!(parse_fragment("SL-HEADERS-S16-2.txt", "---\norder: 100\n---\nx `y`\nz\n").is_ok());
    }

    /// D-X.172 (no spec clause): a tree with the view but without its fragment directory is an error, not a view
    /// left unchecked; a tree with neither (the records tests' scratch trees) has no view.
    #[test]
    fn view_without_fragments_is_an_error() {
        let d = std::env::temp_dir().join(format!("xtask-provenance-none-{}", std::process::id()));
        let _ = fs::remove_dir_all(&d);
        fs::create_dir_all(d.join(ABI)).unwrap();
        assert_eq!(rendered_view(&d).unwrap(), None);
        fs::write(d.join(VIEW), "old\n").unwrap();
        assert!(rendered_view(&d).is_err());
        let _ = fs::remove_dir_all(&d);
    }
}
