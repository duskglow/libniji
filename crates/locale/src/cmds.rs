//! The `locales` package's commands, `locale-gen`, `update-locale` and `validlocale` (UTIL-LOCALE-GEN, spec
//! §31.8, plan/utilities.md §2 and §4, D-31.36 and D-31.37): commands of the shipped `localedef` program chosen by
//! `argv[0]`. Their interfaces come from their manual pages (locale-gen(8), locale.gen(5), update-locale(8),
//! validlocale(8)) and black-box probes of the reference's `locales` package on Debian trixie.
//!
//! * `locale-gen` compiles every locale `/etc/locale.gen` selects in this process, through [`prog::run`] (the
//!   `localedef` command), into the archive; without `--keep-existing` the archive is replaced whole.
//! * `update-locale` edits `/etc/locale.conf` (`/etc/default/locale` is the package's link to it) in place.
//! * `validlocale` says whether a locale is available and, when it is not, prints its `/etc/locale.gen` line.

use crate::prog::{self, Host, Outcome, LOCALE_PATH, MAX_INPUT};
use crate::TryVec;

/// The list of locales `locale-gen` compiles (locale.gen(5)).
pub const LOCALE_GEN: &[u8] = b"/etc/locale.gen";
/// The file `update-locale` edits by default (probed: trixie's default; `/etc/default/locale` links to it).
pub const LOCALE_CONF: &[u8] = b"/etc/locale.conf";
/// The locales the `locales` package can compile, one `<name> <charset>` line each.
pub const SUPPORTED: &[u8] = b"/usr/share/i18n/SUPPORTED";
/// The locale archive `locale-gen` writes.
pub const ARCHIVE: &[u8] = b"/usr/lib/locale/locale-archive";
/// The first line `update-locale` writes into a new file (probed).
const HEADER: &[u8] = b"#  File generated by update-locale\n";
/// The charset `validlocale` suggests for a locale `SUPPORTED` lacks, when `DEFAULTCHARSET` is unset (probed).
const DEFAULT_CHARSET: &[u8] = b"ISO-8859-1";
const ENOENT: i32 = 2;

const UPDATE_USAGE: &[u8] = b"Usage: update-locale [OPTIONS] [LANG=locale] [LC_NUMERIC=locale] ...
Options:
   --help              display this message and exit
   --reset             ignore variables defined in the locale file
   --locale-file=FILE  file containing locale variables
                       (Default: /etc/locale.conf)
   --no-checks         do not perform sanity checks on locale variables
";

/// A failed allocation: the command reports it and stops.
struct NoMem;
type Res<T> = core::result::Result<T, NoMem>;

fn put(v: &mut TryVec<u8>, parts: &[&[u8]]) -> Res<()> {
    for p in parts {
        v.extend_from_slice(p).map_err(|_| NoMem)?;
    }
    Ok(())
}

fn join(parts: &[&[u8]]) -> Res<TryVec<u8>> {
    let mut v = TryVec::new();
    put(&mut v, parts)?;
    Ok(v)
}

/// Print `parts` on `fd` (1 or 2): at once through the host when it can, else into the outcome.
fn say(host: &mut dyn Host, o: &mut Outcome, fd: u8, parts: &[&[u8]]) -> Res<()> {
    let text = join(parts)?;
    if !host.emit(fd, &text) {
        put(if fd == 1 { &mut o.out } else { &mut o.err }, &[&text])?;
    }
    Ok(())
}

fn finish(name: &[u8], r: Res<()>, mut o: Outcome) -> Outcome {
    if r.is_err() {
        o.err.clear();
        let _ = o.err.extend_from_slice(name);
        let _ = o.err.extend_from_slice(b": memory exhausted\n");
        o.status = 4;
    }
    o
}

fn is_blank(b: u8) -> bool {
    b == b' ' || b == b'\t' || b == b'\r'
}

fn trim(mut s: &[u8]) -> &[u8] {
    while let Some((&b, rest)) = s.split_first() {
        if !is_blank(b) {
            break;
        }
        s = rest;
    }
    while let Some((&b, rest)) = s.split_last() {
        if !is_blank(b) {
            break;
        }
        s = rest;
    }
    s
}

/// `s` split at its first run of blanks: (before, after the run); `after` is empty without one.
fn split_field(s: &[u8]) -> (&[u8], &[u8]) {
    match s.iter().position(|&b| is_blank(b)) {
        Some(p) => (s.get(..p).unwrap_or_default(), trim(s.get(p..).unwrap_or_default())),
        None => (s, &[]),
    }
}

/// One selected line of `/etc/locale.gen`: `<locale> <charset>` (locale.gen(5)).
pub struct Entry<'a> {
    /// The locale as written, the name it is stored under (`de_DE`, `en_US.UTF-8`).
    pub locale: &'a [u8],
    /// The rest of the line after the blanks that end the locale: the charmap.
    pub charset: &'a [u8],
}

impl Entry<'_> {
    /// The source file: the locale without its codeset (`ca_ES@valencia` for `ca_ES.UTF-8@valencia`).
    fn source(&self) -> Res<TryVec<u8>> {
        let (base, modifier) = self.parts();
        join(&[base, modifier])
    }

    /// The name printed while it compiles: the charset in place of any codeset (`de_DE.ISO-8859-1`).
    fn display(&self) -> Res<TryVec<u8>> {
        let (base, modifier) = self.parts();
        join(&[base, b".", self.charset, modifier])
    }

    /// (the locale up to its codeset or modifier, `@modifier` or empty).
    fn parts(&self) -> (&[u8], &[u8]) {
        let l = self.locale;
        let at = l.iter().position(|&b| b == b'@').unwrap_or(l.len());
        let modifier = l.get(at..).unwrap_or_default();
        let head = l.get(..at).unwrap_or_default();
        let dot = head.iter().position(|&b| b == b'.').unwrap_or(head.len());
        (head.get(..dot).unwrap_or_default(), modifier)
    }
}

/// The meaningful line `line` of `/etc/locale.gen`: None for a blank or `#` comment line, else the entry (its
/// charset empty when the line has none: a bad entry). Leading and trailing blanks are ignored (probed for leading).
pub fn gen_line(line: &[u8]) -> Option<Entry<'_>> {
    let l = trim(line);
    if l.is_empty() || l.first() == Some(&b'#') {
        return None;
    }
    let (locale, charset) = split_field(l);
    Some(Entry { locale, charset })
}

/// The name a locale is stored under in the archive (`en_US.utf8`).
fn stored(name: &[u8]) -> niji::locale::name::Candidate {
    niji::locale::name::archive_form(&niji::locale::name::parse(name))
}

/// `locale-gen [--keep-existing]`: compile the locales `/etc/locale.gen` selects into the archive.
pub fn locale_gen(args: &[&[u8]], host: &mut dyn Host) -> Outcome {
    let mut o = Outcome::default();
    let r = gen_body(args, host, &mut o);
    finish(b"locale-gen", r, o)
}

fn gen_body(args: &[&[u8]], host: &mut dyn Host, o: &mut Outcome) -> Res<()> {
    // Probed: every other argument is ignored, and a missing /etc/locale.gen is a silent success that leaves
    // the archive alone.
    let keep = args.iter().any(|a| *a == b"--keep-existing");
    let text = match host.read(LOCALE_GEN, MAX_INPUT) {
        Ok(t) => t,
        Err(ENOENT) => return Ok(()),
        Err(e) => {
            let t = host.error_text(e);
            say(host, o, 2, &[b"locale-gen: cannot read ", LOCALE_GEN, b": ", t, b"\n"])?;
            o.status = 1;
            return Ok(());
        }
    };
    let mut existing = TryVec::new();
    if keep {
        if let Ok(d) = host.read(ARCHIVE, 1 << 30) {
            existing = d;
        }
    } else {
        match host.remove(ARCHIVE) {
            Ok(()) | Err(ENOENT) => {}
            Err(e) => {
                let t = host.error_text(e);
                say(host, o, 2, &[b"locale-gen: cannot remove ", ARCHIVE, b": ", t, b"\n"])?;
                o.status = 1;
                return Ok(());
            }
        }
    }
    let archive = crate::archive::Archive::parse(&existing).ok();
    say(host, o, 1, &[b"Generating locales (this might take a while)...\n"])?;
    for line in text.split(|&b| b == b'\n') {
        let Some(e) = gen_line(line) else { continue };
        if e.charset.is_empty() {
            say(host, o, 1, &[b"error: Bad entry '", e.locale, b" ", e.charset, b"'\n"])?;
            continue;
        }
        if archive.as_ref().is_some_and(|a| a.contains(stored(e.locale).as_bytes())) {
            continue;
        }
        say(host, o, 1, &[b"  ", &e.display()?, b"..."])?;
        let source = e.source()?;
        // In this process: the localedef command itself, its messages and statuses unchanged (D-31.36).
        let r = prog::run(&[b"-i", &source, b"-f", e.charset, e.locale], host);
        say(host, o, 1, &[&r.out])?;
        say(host, o, 2, &[&r.err])?;
        say(host, o, 1, &[b" done\n"])?;
    }
    say(host, o, 1, &[b"Generation complete.\n"])?;
    Ok(())
}

/// The available locales: the archive (read once) and the directories under `/usr/lib/locale`.
struct Available {
    archive: TryVec<u8>,
}

impl Available {
    fn new(host: &mut dyn Host) -> Self {
        Available { archive: host.read(ARCHIVE, 1 << 30).unwrap_or_default() }
    }

    /// Whether `setlocale` finds `name`: the built-in `C`, `POSIX` and `C.UTF-8`, the empty name (the
    /// environment's), a name the archive stores, or a directory with an `LC_CTYPE` file.
    fn has(&self, host: &mut dyn Host, name: &[u8]) -> Res<bool> {
        if name.is_empty() || name == b"C" || name == b"POSIX" {
            return Ok(true);
        }
        if name.contains(&b'/') {
            return Ok(false);
        }
        let parts = niji::locale::name::parse(name);
        let s = niji::locale::name::archive_form(&parts);
        if parts.language == b"C" && parts.territory.is_none() && parts.modifier.is_none() && s.as_bytes() == b"C.utf8" {
            return Ok(true);
        }
        if crate::archive::Archive::parse(&self.archive).is_ok_and(|a| a.contains(s.as_bytes()) || a.contains(name)) {
            return Ok(true);
        }
        for n in [name, s.as_bytes()] {
            if host.exists(&join(&[LOCALE_PATH, b"/", n, b"/LC_CTYPE"])?) {
                return Ok(true);
            }
        }
        Ok(false)
    }
}

/// `validlocale LOCALE`: status 0 and a note on standard error when it is available; else status 1, the note,
/// and on standard output the line to add to `/etc/locale.gen` (its `SUPPORTED` entry, or the charset
/// `DEFAULTCHARSET` names, `ISO-8859-1` without one).
pub fn validlocale(argv0: &[u8], args: &[&[u8]], host: &mut dyn Host) -> Outcome {
    let mut o = Outcome::default();
    let r = valid_body(argv0, args, host, &mut o);
    finish(b"validlocale", r, o)
}

fn valid_body(argv0: &[u8], args: &[&[u8]], host: &mut dyn Host, o: &mut Outcome) -> Res<()> {
    let Some(&name) = args.first() else {
        // The program names itself by the path it was run from, as a shell names a script (probed: a bare
        // `validlocale` found on PATH prints `/usr/sbin/validlocale`): a bare argv[0] gets the first PATH
        // directory holding it.
        let mut shown = join(&[argv0])?;
        if !argv0.contains(&b'/') {
            for dir in host.env(b"PATH").unwrap_or_default().split(|&b| b == b':').filter(|d| !d.is_empty()) {
                let p = join(&[dir, b"/", argv0])?;
                if host.exists(&p) {
                    shown = p;
                    break;
                }
            }
        }
        put(&mut o.out, &[b"Usage: ", &shown, b" <locale>\n"])?;
        o.status = 1;
        return Ok(());
    };
    if Available::new(host).has(host, name)? {
        put(&mut o.err, &[b"locale '", name, b"' valid and available\n"])?;
        return Ok(());
    }
    let supported = host.read(SUPPORTED, MAX_INPUT).unwrap_or_default();
    let listed = supported.split(|&b| b == b'\n').map(split_field).find(|(n, _)| *n == name).map(|(_, c)| c);
    let charset = match listed {
        Some(c) => join(&[c])?,
        None => join(&[host.env(b"DEFAULTCHARSET").unwrap_or(DEFAULT_CHARSET)])?,
    };
    put(&mut o.out, &[name, b" ", &charset, b"\n"])?;
    put(&mut o.err, &[b"locale '", name, b"' not available\n"])?;
    o.status = 1;
    Ok(())
}

/// One line of the locale file: its text and, for a `NAME=value` line (optionally after blanks and one `#`),
/// the variable's name and whether the line is active (not commented).
struct Line {
    text: TryVec<u8>,
    var: Option<(TryVec<u8>, bool)>,
}

fn is_name_byte(b: u8, first: bool) -> bool {
    b == b'_' || b.is_ascii_alphabetic() || (!first && b.is_ascii_digit())
}

/// (name, active, value) of a variable line: `[blanks][#][blanks]NAME=value` (probed: `  LC_PAPER=C` and
/// `#LANG=C` are variables, `export LC_TIME=C` is not).
fn parse_var(line: &[u8]) -> Option<(&[u8], bool, &[u8])> {
    let mut s = trim(line);
    let mut active = true;
    if let Some(rest) = s.strip_prefix(b"#") {
        s = trim(rest);
        active = false;
    }
    let eq = s.iter().position(|&b| b == b'=')?;
    let name = s.get(..eq)?;
    let mut bytes = name.iter();
    if !bytes.next().is_some_and(|&b| is_name_byte(b, true)) || !bytes.all(|&b| is_name_byte(b, false)) {
        return None;
    }
    Some((name, active, s.get(eq.saturating_add(1)..).unwrap_or_default()))
}

fn var_line(text: TryVec<u8>) -> Res<Line> {
    let var = match parse_var(&text) {
        Some((n, a, _)) => Some((join(&[n])?, a)),
        None => None,
    };
    Ok(Line { text, var })
}

/// The active value of `name` in `lines`, without one pair of surrounding double quotes.
fn value_of<'l>(lines: &'l [Line], name: &[u8]) -> Option<&'l [u8]> {
    let l = lines.iter().find(|l| l.var.as_ref().is_some_and(|(n, a)| *a && n.as_slice() == name))?;
    let v = parse_var(&l.text)?.2;
    Some(v.strip_prefix(b"\"").and_then(|v| v.strip_suffix(b"\"")).unwrap_or(v))
}

/// Comment out the active line of `name`, if any (`#` before its text, probed).
fn disable(lines: &mut [Line], name: &[u8]) -> Res<()> {
    for l in lines.iter_mut() {
        if let Some((n, active)) = l.var.as_mut() {
            if *active && n.as_slice() == name {
                let text = join(&[b"#", &l.text])?;
                l.text = text;
                *active = false;
            }
        }
    }
    Ok(())
}

/// The language of a locale name or `LANGUAGE` entry: up to `_`, `.` or `@`.
fn language(name: &[u8]) -> &[u8] {
    let end = name.iter().position(|&b| matches!(b, b'_' | b'.' | b'@')).unwrap_or(name.len());
    name.get(..end).unwrap_or_default()
}

/// `update-locale [--reset] [--no-checks] [--locale-file FILE] [NAME=value | NAME]...`.
pub fn update_locale(args: &[&[u8]], host: &mut dyn Host) -> Outcome {
    let mut o = Outcome::default();
    let r = update_body(args, host, &mut o);
    finish(b"update-locale", r, o)
}

fn update_body(args: &[&[u8]], host: &mut dyn Host, o: &mut Outcome) -> Res<()> {
    let (mut reset, mut checks) = (false, true);
    let mut file: &[u8] = LOCALE_CONF;
    let mut ops: TryVec<&[u8]> = TryVec::new();
    let mut i = 0;
    let mut operands_only = false;
    while let Some(&a) = args.get(i) {
        i = i.saturating_add(1);
        if operands_only || a.len() < 2 || a.first() != Some(&b'-') {
            ops.push(a).map_err(|_| NoMem)?;
            continue;
        }
        if a == b"--" {
            operands_only = true;
            continue;
        }
        let opt = a.strip_prefix(b"--").unwrap_or_else(|| a.get(1..).unwrap_or_default());
        let (name, value) = match opt.iter().position(|&b| b == b'=') {
            Some(p) => (opt.get(..p).unwrap_or_default(), opt.get(p.saturating_add(1)..)),
            None => (opt, None),
        };
        match name {
            b"help" => {
                put(&mut o.err, &[UPDATE_USAGE])?;
                return Ok(());
            }
            b"reset" => reset = true,
            b"no-checks" => checks = false,
            b"locale-file" => match value.or_else(|| args.get(i).copied()) {
                Some(v) => {
                    if value.is_none() {
                        i = i.saturating_add(1);
                    }
                    file = v;
                }
                None => put(&mut o.err, &[b"Option locale-file requires an argument\n"])?,
            },
            _ => put(&mut o.err, &[b"Unknown option: ", name, b"\n"])?,
        }
    }
    let mut lines: TryVec<Line> = TryVec::new();
    match host.read(file, MAX_INPUT) {
        Ok(text) if !text.is_empty() => {
            let body = text.strip_suffix(b"\n").unwrap_or(&text);
            for l in body.split(|&b| b == b'\n') {
                // Probed: an empty line is written back as `#`.
                let t = if l.is_empty() { join(&[b"#"])? } else { join(&[l])? };
                lines.push(var_line(t)?).map_err(|_| NoMem)?;
            }
        }
        Ok(_) | Err(ENOENT) => lines.push(var_line(join(&[HEADER.strip_suffix(b"\n").unwrap_or(HEADER)])?)?).map_err(|_| NoMem)?,
        Err(e) => {
            put(&mut o.err, &[b"update-locale: Unable to read ", file, b": ", host.error_text(e), b"\n"])?;
            o.status = 2;
            return Ok(());
        }
    }
    if reset {
        // Every active variable the operands do not name is commented out.
        let names: TryVec<TryVec<u8>> = {
            let mut v = TryVec::new();
            for l in lines.iter() {
                if let Some((n, true)) = &l.var {
                    v.push(join(&[n])?).map_err(|_| NoMem)?;
                }
            }
            v
        };
        for n in names.iter() {
            let named = ops.iter().any(|op| op.split(|&b| b == b'=').next() == Some(n.as_slice()));
            if !named {
                disable(&mut lines, n)?;
            }
        }
    }
    for &op in ops.iter() {
        match op.iter().position(|&b| b == b'=') {
            None => disable(&mut lines, op)?,
            Some(p) => {
                let name = op.get(..p).unwrap_or_default();
                let at = lines.iter().position(|l| l.var.as_ref().is_some_and(|(n, _)| n.as_slice() == name));
                let new = Line { text: join(&[op])?, var: Some((join(&[name])?, true)) };
                match at.and_then(|k| lines.get_mut(k)) {
                    Some(l) => *l = new,
                    None => lines.push(new).map_err(|_| NoMem)?,
                }
            }
        }
    }
    // Both checks are the sanity checks `--no-checks` skips, availability first: a refused setting leaves
    // LANGUAGE in the error line and unwarned (probed).
    if checks {
        let avail = Available::new(host);
        let mut bad = false;
        for l in lines.iter() {
            let Some((n, true)) = &l.var else { continue };
            if n.as_slice() == b"LANG" || n.starts_with(b"LC_") {
                let v = value_of(&lines, n).unwrap_or_default();
                if !avail.has(host, v)? {
                    bad = true;
                }
            }
        }
        if bad {
            put(&mut o.err, &[b"*** update-locale: Error: invalid locale settings: "])?;
            for l in lines.iter() {
                if let Some((_, true)) = &l.var {
                    put(&mut o.err, &[b" ", trim(l.text.strip_prefix(b"#").unwrap_or(&l.text))])?;
                }
            }
            put(&mut o.err, &[b"\n"])?;
            o.status = 255;
            return Ok(());
        }
        // LANGUAGE lists languages for messages; one whose first language is not LC_ALL's (or else LANG's) is
        // disabled with a warning, unless that locale is C or POSIX (probed).
        let target = [&b"LC_ALL"[..], b"LANG"].into_iter().find_map(|n| value_of(&lines, n).filter(|v| !v.is_empty()).map(|v| (n, v)));
        if let (Some((tname, tval)), Some(langs)) = (target, value_of(&lines, b"LANGUAGE").filter(|v| !v.is_empty())) {
            let first = langs.split(|&b| b == b':').next().unwrap_or_default();
            if tval != b"C" && tval != b"POSIX" && language(first) != language(tval) {
                let (tname, tval, langs) = (join(&[tname])?, join(&[tval])?, join(&[langs])?);
                put(&mut o.out, &[b"*** update-locale: Warning: LANGUAGE (", &langs, b") is not compatible with ", &tname, b" (", &tval, b"). Disabling it.\n"])?;
                disable(&mut lines, b"LANGUAGE")?;
            }
        }
    }
    let mut out = TryVec::new();
    for l in lines.iter() {
        put(&mut out, &[&l.text, b"\n"])?;
    }
    if let Err(e) = host.write(file, &out) {
        put(&mut o.err, &[b"update-locale: Unable to write ", file, b": ", host.error_text(e), b"\n"])?;
        o.status = 2;
    }
    Ok(())
}

/// Run the command `argv0` names (its last path component): `locale-gen`, `update-locale`, `validlocale`, or
/// None for any other name (the program is `localedef`).
pub fn by_name(argv0: &[u8], args: &[&[u8]], host: &mut dyn Host) -> Option<Outcome> {
    let base = argv0.rsplit(|&b| b == b'/').next().unwrap_or(argv0);
    match base {
        b"locale-gen" => Some(locale_gen(args, host)),
        b"update-locale" => Some(update_locale(args, host)),
        b"validlocale" => Some(validlocale(argv0, args, host)),
        _ => None,
    }
}
