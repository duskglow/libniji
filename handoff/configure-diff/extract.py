#!/usr/bin/env python3
"""CONFIGURE-DIFF extractor: every probe answer of one configure run as "key<TAB>value" lines.

Reads <run>/pkgs/<pkg>/out/<side>.tar (inside.sh) and writes <run>/probes/<pkg>.<side>.tsv. Keys:
  ac:<dir>:<var>        autoconf cache variables (config.log "Cache variables" section)
  acout:<dir>:<var>     autoconf output variables that carry probe results (LIBS, *_LIBS, LIBOBJS, ...)
  h:<file>:<macro>      #define / #undef lines of generated headers (config.h and friends); value UNDEF if #undef
  perl:<dir>:<var>      perl's Configure answers (config.sh: d_*, i_*, *size, *type, ...)
  meson:<dir>:<check>   meson-log.txt check lines ("Has header", "Checking for function", "Checking if .. compiles",
                        "Header .. has symbol", "Checking for size of", ...); " (cached)" removed
  cmake:<dir>:<var>     CMakeCache.txt INTERNAL entries (HAVE_*, *_COMPILES, SIZEOF_*, ...)
<dir> is the file's directory inside the build tree, so the same probe in two sub-configures stays two keys.
Usage: extract.py <run dir> [<pkg> ...]
"""
import io
import os
import re
import sys
import tarfile

SIDES = ("stockA", "stockB", "niji", "s239")
ACOUT = re.compile(r"^(LIBS|LIBOBJS|LTLIBOBJS|ALLOCA|\w*_LIBS|\w*LIBS|POW_LIB|LIBM|LIB_\w+|\w*_LIBADD)$")
PERLKEY = re.compile(r"^(d_\w+|i_\w+|\w*size|\w*type|\w*types|sig_\w+|libs|perllibs|\w*_r_proto|ccflags|ldflags|"
                     r"usethreads|useithreads|uselargefiles|use64bitint|use64bitall|longdblkind|doublekind|"
                     r"nvsize|ivsize|uvsize|selectminbits|sched_yield|stdchar|groupstype|direntrytype|"
                     r"alignbytes|randbits|drand01|seedfunc|ptrsize|byteorder|known_extensions|static_ext|"
                     r"dynamic_ext|extensions|nonxs_ext)$")
MESON = re.compile(r"^(Has header|Header|Checking for function|Checking for type|Checking for size of|"
                   r"Checking for alignment of|Checking if|Checking whether type|Fetching value of define|"
                   r"Compiler for \S+ supports|Library|Checking for value of define|Run-time dependency)\b(.*)$")
DEFINE = re.compile(r"^\s*#\s*define\s+(\w+)(?:\(([^)]*)\))?\s*(.*?)\s*$")
UNDEF = re.compile(r"^\s*/\*\s*#\s*undef\s+(\w+)\s*\*/\s*$|^\s*#\s*undef\s+(\w+)\s*$")
SHVAR = re.compile(r"^([A-Za-z_]\w*)=(.*)$")


def unquote(v):
    v = v.strip()
    if len(v) >= 2 and v[0] == v[-1] and v[0] in "'\"":
        v = v[1:-1]
    if v.startswith("$'") and v.endswith("'"):
        v = v[2:-1]
    return v


def config_log(dirn, text, out):
    sect = None
    for line in text.splitlines():
        if line.startswith("## ") and line.rstrip().endswith("##"):
            t = line.strip("# \n")
            if not t.strip("-"):
                continue  # the dashed rule around a section title
            sect = {"Cache variables.": "ac", "Output variables.": "acout"}.get(t)
            continue
        if sect is None or line.startswith("##"):
            continue
        m = SHVAR.match(line)
        if not m:
            continue
        k, v = m.group(1), unquote(m.group(2))
        if sect == "ac":
            out["ac:%s:%s" % (dirn, k)] = v
        elif ACOUT.match(k):
            out["acout:%s:%s" % (dirn, k)] = v


def header(path, text, out):
    # Only headers that look generated by a configure step (a #define/#undef config header), not copied sources.
    defs = {}
    for line in text.splitlines():
        m = DEFINE.match(line)
        if m:
            name = m.group(1)
            val = m.group(3) if m.group(2) is None else "(%s) %s" % (m.group(2), m.group(3))
            defs[name] = val if name not in defs else defs[name] + " | " + val
            continue
        m = UNDEF.match(line)
        if m:
            name = m.group(1) or m.group(2)
            defs.setdefault(name, "UNDEF")
    for k, v in defs.items():
        out["h:%s:%s" % (path, k)] = v


def perl_config(dirn, text, out):
    for line in text.splitlines():
        m = SHVAR.match(line)
        if m and PERLKEY.match(m.group(1)):
            out["perl:%s:%s" % (dirn, m.group(1))] = unquote(m.group(2))


def meson_log(dirn, text, out):
    for line in text.splitlines():
        m = MESON.match(line)
        if not m:
            continue
        s = re.sub(r"\x1b\[[0-9;]*m", "", line).replace(" (cached)", "").replace(" (Cached)", "")
        s = re.sub(r"\s+", " ", s.strip())
        if ":" not in s:
            continue
        k, v = s.rsplit(":", 1)
        if m.group(1) == "Run-time dependency":
            # "Run-time dependency x found: YES 1.2" -> key without found/version noise
            k = re.sub(r" found$", "", k.strip())
        out["meson:%s:%s" % (dirn, k.strip())] = v.strip()


def cmake_cache(dirn, text, out):
    for line in text.splitlines():
        if line.startswith(("#", "//")) or ":INTERNAL=" not in line:
            continue
        k, v = line.split(":INTERNAL=", 1)
        if k.startswith("CMAKE_") or k.endswith(("_ADVANCED", "-ADVANCED")) or k.startswith("_"):
            continue
        out["cmake:%s:%s" % (dirn, k)] = v


def extract(tarpath):
    out = {}
    with tarfile.open(tarpath) as tf:
        for ti in tf.getmembers():
            if not ti.isfile():
                continue
            name = ti.name[2:] if ti.name.startswith("./") else ti.name
            base = os.path.basename(name)
            dirn = os.path.dirname(name) or "."
            text = tf.extractfile(ti).read().decode("utf-8", "replace")
            if base == "config.log":
                config_log(dirn, text, out)
            elif base == "meson-log.txt":
                meson_log(os.path.dirname(dirn) or ".", text, out)
            elif base == "CMakeCache.txt":
                cmake_cache(dirn, text, out)
            elif base == "config.sh":
                perl_config(dirn, text, out)
            elif base.endswith(".h"):
                header(name, text, out)
    return out


def main():
    run = sys.argv[1]
    pkgs = sys.argv[2:] or sorted(os.listdir(os.path.join(run, "pkgs")))
    os.makedirs(os.path.join(run, "probes"), exist_ok=True)
    for p in pkgs:
        for s in SIDES:
            t = os.path.join(run, "pkgs", p, "out", s + ".tar")
            if not os.path.exists(t):
                continue
            try:
                d = extract(t)
            except (tarfile.TarError, OSError) as e:
                print("extract: %s %s: %s" % (p, s, e))
                continue
            with io.open(os.path.join(run, "probes", "%s.%s.tsv" % (p, s)), "w") as f:
                for k in sorted(d):
                    f.write("%s\t%s\n" % (k, d[k].replace("\t", " ").replace("\n", " ")))


if __name__ == "__main__":
    main()
