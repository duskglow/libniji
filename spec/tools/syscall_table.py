#!/usr/bin/env python3
"""spec/abi/syscalls.tsv: the system call names and numbers of the kernel's user-space API (SL-HEADERS-S09).

The source is the kernel UAPI header `asm/unistd_64.h` of the linux-libc-dev package (kernel documentation of the
x86-64 system call table), never a libc header: each `#define __NR_<name> <n>` line is one row. `sys/syscall.h`
defines `SYS_<name>` as `__NR_<name>` for each row (xtask/src/headers.rs, marker `@@syscalls`).

usage: syscall_table.py [--uapi DIR] [--out FILE]   (default DIR /usr/include/x86_64-linux-gnu, FILE spec/abi/syscalls.tsv)
"""
import argparse
import os
import re
import subprocess

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--uapi", default="/usr/include/x86_64-linux-gnu")
    ap.add_argument("--out", default=os.path.join(ROOT, "spec/abi/syscalls.tsv"))
    args = ap.parse_args()
    path = os.path.join(args.uapi, "asm/unistd_64.h")
    rows = []
    with open(path) as f:
        for line in f:
            m = re.match(r"#define __NR_([A-Za-z0-9_]+)\s+([0-9]+)\s*$", line)
            if m:
                rows.append((int(m.group(2)), m.group(1)))
    rows.sort()
    pkg = subprocess.run(["dpkg-query", "-W", "-f=${Version}", "linux-libc-dev"], capture_output=True, text=True).stdout.strip()
    with open(args.out, "w") as o:
        o.write("# x86-64 system calls: name and number from the kernel UAPI header asm/unistd_64.h (linux-libc-dev %s).\n" % (pkg or "unknown"))
        o.write("# Generated by spec/tools/syscall_table.py; sys/syscall.h defines SYS_<name> as __NR_<name> for each row.\n")
        o.write("name\tnumber\n")
        for n, name in rows:
            o.write("%s\t%d\n" % (name, n))
    print("syscall_table: %d rows from %s (linux-libc-dev %s)" % (len(rows), path, pkg))


if __name__ == "__main__":
    main()
